//! Real source inspection. Provisioning belongs to the Docker harness lane.
use skedaddle::{
    Criticality, ItemStatus,
    definition::{ObjectKind, ObjectSelector},
    pg::preflight::{Options, assess},
};
use tokio_postgres::Client;

async fn connection(key: &str) -> Option<Client> {
    let Some(path) = std::env::var_os("SKEDADDLE_TEST_CONFIG") else {
        eprintln!(
            "SKIP pg_preflight: Docker harness SKEDADDLE_TEST_CONFIG is absent; no PostgreSQL was inspected"
        );
        return None;
    };
    let config: serde_json::Value =
        serde_json::from_slice(&std::fs::read(path).expect("read harness config")).unwrap();
    let Some(dsn) = config[key].as_str() else {
        eprintln!(
            "SKIP pg_preflight: harness config lacks {key}; Docker lane must provision this source"
        );
        return None;
    };
    // Never include the DSN or driver error (which may contain secrets) in output.
    let Ok((client, driver)) = tls_connect(dsn).await else {
        panic!("configured PostgreSQL harness source failed to connect");
    };
    tokio::spawn(async move { assert!(driver.await.is_ok(), "harness connection failed") });
    Some(client)
}

fn table(name: &str) -> ObjectSelector {
    ObjectSelector {
        schema: "public".into(),
        name: name.into(),
        kind: ObjectKind::Table,
        exclude_columns: Vec::new(),
    }
}

#[tokio::test]
async fn column_behavior_evidence_controls_partial_destination_writes() {
    if std::env::var_os("SKEDADDLE_TEST_CONFIG").is_none() {
        use std::io::Write;
        let _ = writeln!(
            std::io::stderr().lock(),
            "SKIP pg_preflight column behavior: Docker harness SKEDADDLE_TEST_CONFIG absent; live NOT NULL/DEFAULT/GENERATED/IDENTITY evidence NOT QUALIFIED"
        );
        return;
    }
    let Some(mut client) = connection("pg").await else {
        return;
    };
    let tx = client.transaction().await.unwrap();
    let schema = format!("gd49_k4_behavior_{}", std::process::id());
    tx.batch_execute(&format!(
        "CREATE SCHEMA {schema}; CREATE TABLE {schema}.behavior (
            id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            required text NOT NULL,
            nullable text,
            defaulted text NOT NULL DEFAULT 'server default',
            generated bigint GENERATED ALWAYS AS (id+1) STORED NOT NULL,
            identity_default bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL)"
    ))
    .await
    .unwrap();
    let object = ObjectSelector {
        schema: schema.clone(),
        name: "behavior".into(),
        kind: ObjectKind::Table,
        exclude_columns: Vec::new(),
    };
    let snapshot = skedaddle::pg::preflight::collect_in(&tx, std::slice::from_ref(&object))
        .await
        .unwrap();
    let columns = snapshot
        .observations
        .iter()
        .find(|o| o.check == skedaddle::pg::preflight::Check::ColumnTypes)
        .unwrap();
    assert!(columns.error.is_none(), "{:?}", columns.error);
    for (name, not_null, has_default, generated, identity) in [
        ("id", true, false, false, true),
        ("required", true, false, false, false),
        ("nullable", false, false, false, false),
        ("defaulted", true, true, false, false),
        ("generated", true, true, true, false),
        ("identity_default", true, false, false, true),
    ] {
        let row = columns.rows.iter().find(|r| r["column"] == name).unwrap();
        for (field, expected) in [
            ("not_null", not_null),
            ("has_default", has_default),
            ("generated", generated),
            ("identity", identity),
        ] {
            assert_eq!(row[field].as_bool(), Some(expected), "{name}.{field}");
        }
    }
    let selection = skedaddle::pg::catalog::TableSelection {
        schema,
        name: "behavior".into(),
        columns: vec!["id".into()],
    };
    let error = skedaddle::pg::catalog::build(
        &snapshot,
        &snapshot,
        std::slice::from_ref(&selection),
        0,
        true,
    )
    .unwrap_err();
    assert_eq!(error.column, "required");
    assert!(error.reason.contains("NOT NULL"));
    tx.batch_execute(&format!(
        "ALTER TABLE {}.behavior ALTER COLUMN required SET DEFAULT 'qualified default'",
        selection.schema
    ))
    .await
    .unwrap();
    let snapshot = skedaddle::pg::preflight::collect_in(&tx, &[object])
        .await
        .unwrap();
    let catalog = skedaddle::pg::catalog::build(&snapshot, &snapshot, &[selection], 0, true)
        .unwrap()
        .remove(0);
    assert_eq!(catalog.destination.columns.len(), 1);
    assert_eq!(catalog.destination.columns[0].name, "id");
    tx.rollback().await.unwrap();
}

#[tokio::test]
#[ignore = "requires Docker harness SKEDADDLE_TEST_CONFIG with pg; no containers are started by this test"]
async fn preflight_reports_each_item_with_evidence() {
    let Some(mut client) = connection("pg").await else {
        return;
    };
    let transaction = client.transaction().await.unwrap();
    let schema = format!("gd49_p5c_inventory_{}", std::process::id());
    transaction.batch_execute(&format!("CREATE SCHEMA {schema};
        CREATE TABLE {schema}.inventory (
            id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            nullable_key text UNIQUE,
            generated_id bigint GENERATED ALWAYS AS (id+1) STORED,
            serial_id bigserial);
        INSERT INTO {schema}.inventory(nullable_key) VALUES (NULL),(NULL),('distinct');
        CREATE VIEW {schema}.inventory_view AS SELECT id FROM {schema}.inventory;
        CREATE FUNCTION {schema}.audit() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN RETURN NEW; END';
        CREATE TRIGGER audit BEFORE INSERT ON {schema}.inventory FOR EACH ROW EXECUTE FUNCTION {schema}.audit();
        CREATE TABLE {schema}.partitioned (id int PRIMARY KEY) PARTITION BY RANGE(id);
        CREATE TABLE {schema}.leaf PARTITION OF {schema}.partitioned FOR VALUES FROM (0) TO (100);"))
        .await.unwrap();
    let selected = [
        ObjectSelector {
            schema: schema.clone(),
            name: "inventory".into(),
            kind: ObjectKind::Table,
            exclude_columns: Vec::new(),
        },
        ObjectSelector {
            schema,
            name: "partitioned".into(),
            kind: ObjectKind::Table,
            exclude_columns: Vec::new(),
        },
    ];
    let snapshot = skedaddle::pg::preflight::collect_in(&transaction, &selected)
        .await
        .unwrap();
    for observation in &snapshot.observations {
        assert!(
            observation.error.is_none(),
            "{:?}: {:?}",
            observation.check,
            observation.error
        );
    }
    let report = skedaddle::pg::preflight::classify(
        "harness-definition",
        &snapshot,
        &Options::default(),
        |_| true,
    );
    for id in [
        "version",
        "wal_level",
        "slot_headroom",
        "wal_sender_headroom",
        "wal_retention",
        "wal_disk",
        "replication_privilege",
        "database_create",
        "event_trigger_privilege",
        "origin_grants",
        "views",
        "routines",
        "extensions",
        "large_objects",
        "prepared_transactions",
        "long_transactions",
        "restart_locks",
        "table",
        "key",
        "replica_identity",
        "nullable_key_duplicates",
        "mutable_keys",
        "column_types",
        "sequences",
        "generated_columns",
        "identity_columns",
        "triggers",
        "partitions",
        "grants",
    ] {
        let item = report
            .items
            .iter()
            .find(|i| i.id == format!("pg.{id}"))
            .unwrap_or_else(|| panic!("missing {id}"));
        assert!(!item.remediation.is_empty());
        assert!(
            item.evidence
                .iter()
                .any(|e| e.source.starts_with("SELECT ") && !e.description.is_empty()),
            "{id}: missing exact SQL and result"
        );
        assert!(!item.sampled);
    }
    for (id, expected) in [
        ("key", ItemStatus::Supported),
        (
            "nullable_key_duplicates",
            ItemStatus::RequiresExternalChange,
        ),
        ("triggers", ItemStatus::Unverified),
        ("generated_columns", ItemStatus::SupportedWithTransformation),
    ] {
        assert_eq!(
            report
                .items
                .iter()
                .find(|i| i.id == format!("pg.{id}"))
                .unwrap()
                .status,
            expected,
            "{id}"
        );
    }
    transaction.rollback().await.unwrap();
    // Missing selected objects must fail closed, even when the inventory is empty.
    let report = assess(
        &mut client,
        "missing",
        &[table("gd49_p5c_absent")],
        &Options::default(),
        |_| true,
    )
    .await
    .unwrap();
    assert!(report.blocking().iter().any(|i| i.id == "pg.table"));
}

#[tokio::test]
#[ignore = "requires Docker harness pg_replica_wal configured with wal_level=replica"]
async fn wal_level_replica_blocks() {
    let Some(mut client) = connection("pg_replica_wal").await else {
        return;
    };
    let report = assess(&mut client, "replica-wal", &[], &Options::default(), |_| {
        true
    })
    .await
    .unwrap();
    let item = report
        .items
        .iter()
        .find(|i| i.id == "pg.wal_level")
        .unwrap();
    assert_eq!(item.status, ItemStatus::RequiresExternalChange);
    assert_eq!(item.criticality, Criticality::Critical);
    assert!(item.remediation.contains("restart"));
    assert!(item.evidence[0].description.contains("replica"));
}

#[tokio::test]
#[ignore = "requires Docker harness SKEDADDLE_TEST_CONFIG with pg; no containers are started by this test"]
async fn keyless_table_blocks_with_remedies() {
    let Some(mut client) = connection("pg").await else {
        return;
    };
    // Transaction-local fixture: rollback removes it even if this test panics.
    let transaction = client.transaction().await.unwrap();
    let name = format!("gd49_p5c_keyless_{}", std::process::id());
    transaction
        .batch_execute(&format!("CREATE TABLE public.{name} (value text)"))
        .await
        .unwrap();
    // collect accepts an existing transaction so fixture DDL never escapes it.
    let snapshot = skedaddle::pg::preflight::collect_in(&transaction, &[table(&name)])
        .await
        .unwrap();
    let report =
        skedaddle::pg::preflight::classify("keyless", &snapshot, &Options::default(), |_| true);
    let item = report.items.iter().find(|i| i.id == "pg.key").unwrap();
    assert_eq!(item.status, ItemStatus::Unsupported);
    assert!(item.remediation.contains("non-null unique"));
    assert!(item.remediation.contains("exclude"));
    assert!(report.blocking().contains(&item));
    transaction.rollback().await.unwrap();
}

// The harness CA is explicit; missing trust is a failure once a DB gate is set.
fn tls_config(postgres: tokio_postgres::Config) -> skedaddle::pg::tls::Config {
    let path = std::env::var_os("SKEDADDLE_TEST_CONFIG").expect("TLS harness config required");
    let config: serde_json::Value =
        serde_json::from_slice(&std::fs::read(path).expect("read TLS harness config"))
            .expect("TLS harness JSON");
    let ca_pem = config["ca_pem"]
        .as_str()
        .or_else(|| config["replication"]["ca_pem"].as_str())
        .expect("harness ca_pem or replication.ca_pem required");
    skedaddle::pg::tls::Config::new(postgres, ca_pem)
}

async fn tls_connect(
    dsn: &str,
) -> std::result::Result<
    (tokio_postgres::Client, skedaddle::pg::tls::Driver),
    skedaddle::pg::tls::Error,
> {
    let config = tls_config(dsn.parse().expect("harness PostgreSQL configuration"));
    let (client, driver, transport) =
        skedaddle::pg::tls::connect(&config, &skedaddle::security::TlsPolicy::Required).await?;
    assert!(transport.encrypted());
    assert!(transport.warnings.is_empty());
    Ok((client, driver))
}
