//! Real PostgreSQL qualification. No Docker is started by this test binary.
//! Use TWO disposable databases and a superuser; source needs wal_level=logical
//! and the test_decoding plugin for measured_interruption_reported.
//! Set SKEDADDLE_CUTOVER_SOURCE_URL and SKEDADDLE_CUTOVER_DESTINATION_URL.
//! Fixture files live only under SKEDADDLE_TEST_ROOT on J:.

mod support;

use skedaddle::{
    cutover::{self, *},
    pg::{activate, fence},
};
use std::{
    cell::RefCell, collections::BTreeSet, path::PathBuf, rc::Rc, sync::Mutex, time::Duration,
};
use tokio_postgres::SimpleQueryMessage;

static SERIAL: Mutex<()> = Mutex::new(());
#[derive(Clone)]
struct Pg {
    runtime: Rc<tokio::runtime::Runtime>,
    client: Rc<tokio_postgres::Client>,
}
impl Pg {
    fn open(runtime: Rc<tokio::runtime::Runtime>, url: &str) -> Self {
        let (client, connection) = runtime
            .block_on(tls_connect(url))
            .expect("connect to disposable cutover PG");
        runtime.spawn(async move {
            if let Err(e) = connection.await {
                eprintln!("cutover test PG transport: {e}");
            }
        });
        Self {
            runtime,
            client: Rc::new(client),
        }
    }
    fn sql(&mut self, sql: &str) -> fence::Rows {
        fence::Connection::query(self, sql, Duration::from_secs(15)).unwrap()
    }
}
impl fence::Connection for Pg {
    fn query(&mut self, sql: &str, timeout: Duration) -> std::result::Result<fence::Rows, String> {
        let result = self
            .runtime
            .block_on(async { tokio::time::timeout(timeout, self.client.simple_query(sql)).await });
        match result {
            Ok(Ok(messages)) => Ok(messages
                .into_iter()
                .filter_map(|m| match m {
                    SimpleQueryMessage::Row(row) => Some(
                        (0..row.len())
                            .map(|i| row.get(i).unwrap_or("").to_owned())
                            .collect(),
                    ),
                    _ => None,
                })
                .collect()),
            failure => {
                // fence::Connection requires failed batches to be rolled back.
                let _ = self.runtime.block_on(self.client.batch_execute("ROLLBACK"));
                Err(format!("cutover test query failed: {failure:?}"))
            }
        }
    }
}
fn lit(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}
fn gated(name: &str) -> Option<(String, String)> {
    let source = std::env::var("SKEDADDLE_CUTOVER_SOURCE_URL").ok();
    let destination = std::env::var("SKEDADDLE_CUTOVER_DESTINATION_URL").ok();
    match (source, destination) {
        (Some(s), Some(d)) => Some((s, d)),
        _ => {
            eprintln!(
                "SKIP {name}: set SKEDADDLE_CUTOVER_SOURCE_URL and SKEDADDLE_CUTOVER_DESTINATION_URL to disposable real PostgreSQL databases (superuser; no Docker runs here)"
            );
            None
        }
    }
}

struct Fixture {
    source: cutover::pg::Source<Pg, fn() -> std::result::Result<(), String>>,
    target: cutover::pg::Target<Pg>,
    schema: String,
    installation: String,
    source_role: String,
    destination_role: String,
    slot: Option<String>,
    key: Key,
    epoch: i64,
    reverse_owner: Option<skedaddle::coordinator::epoch::Coordinator>,
}
impl Fixture {
    fn new(urls: (String, String), logical: bool) -> Self {
        let runtime = Rc::new(tokio::runtime::Runtime::new().unwrap());
        let mut source = Pg::open(runtime.clone(), &urls.0);
        let mut destination = Pg::open(runtime, &urls.1);
        let identity = "SELECT current_database(),system_identifier::text FROM pg_control_system()";
        assert_ne!(
            source.sql(identity),
            destination.sql(identity),
            "use two distinct disposable databases"
        );
        let suffix = uuid::Uuid::new_v4().simple().to_string();
        // This disposable, serialized fixture now uses the coordinator's real
        // first ownership epoch for source, destination and cutover alike.
        let epoch = 1;
        let schema = format!("p10b_{suffix}");
        let installation = format!("p10b_{}", &suffix[..24]);
        let source_role = format!("p10b_s_{suffix}");
        let destination_role = format!("p10b_d_{suffix}");
        let mut tables = Vec::new();
        for (c, role) in [
            (&mut source, &source_role),
            (&mut destination, &destination_role),
        ] {
            c.sql(&format!("CREATE ROLE {role} LOGIN; CREATE SCHEMA {schema}; CREATE TABLE {schema}.items(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,v text NOT NULL); INSERT INTO {schema}.items(v) VALUES('one'); GRANT USAGE ON SCHEMA {schema} TO {role}; GRANT SELECT,INSERT,UPDATE,DELETE ON {schema}.items TO {role}; GRANT USAGE ON SEQUENCE {schema}.items_id_seq TO {role};"));
            let owner = c.sql("SELECT current_user")[0][0].clone();
            tables.push(fence::Table {
                schema: schema.clone(),
                name: "items".into(),
                owner,
            });
        }
        let apps = BTreeSet::from([source_role.clone()]);
        // Explicit acknowledgement of the fixture's privileged administrators.
        let mut acknowledged = BTreeSet::new();
        for row in source.sql("SELECT rolname FROM pg_roles") {
            for kind in [
                fence::ResidualKind::Superuser,
                fence::ResidualKind::TableOwner,
                fence::ResidualKind::BypassRls,
                fence::ResidualKind::OutOfScopeWriter,
            ] {
                acknowledged.insert(fence::ResidualPrincipal {
                    role: row[0].clone(),
                    kind,
                });
            }
        }
        let state = fence::Fence::new(fence::FenceConfig {
            epoch,
            applications: apps,
            tables: vec![tables[0].clone()],
            acknowledged,
            deadline_ms: 10_000,
        })
        .unwrap();
        let mut destination_state = activate::DestinationFence::new(activate::Config {
            epoch,
            applications: BTreeSet::from([destination_role.clone()]),
            tables: vec![tables[1].clone()],
            timeout_ms: 10_000,
            post_activate: None,
        })
        .unwrap();
        while destination_state.next != activate::Step::Fenced {
            destination_state
                .execute_next(&mut destination, &mut |_| Ok(()))
                .unwrap();
        }
        destination.sql(&format!("CREATE TABLE {schema}.applied(cutover text PRIMARY KEY,epoch bigint NOT NULL,lsn text NOT NULL); CREATE TABLE {schema}.owner(epoch bigint NOT NULL,coordinator text NOT NULL); INSERT INTO {schema}.owner VALUES({epoch},'fixture');"));
        let source_version = source.sql("SHOW server_version_num")[0][0].parse().unwrap();
        let trigger = skedaddle::pg::ddl::TriggerSql::new(&installation, source_version).unwrap();
        source.sql(&trigger.install);
        let slot = logical.then(|| format!("p10b_{suffix}"));
        if let Some(slot) = &slot {
            source.sql(&format!(
                "SELECT slot_name FROM pg_create_logical_replication_slot({},'test_decoding')",
                lit(slot)
            ));
        }
        let reverse_owner = logical.then(|| {
            let journal = support::journal(
                support::fs_store(support::scratch("cutover-proof")),
                &schema,
            );
            let mut owner = support::coordinator(journal, "cutover-owner");
            destination.runtime.block_on(owner.acquire()).unwrap();
            owner
        });
        let coordinator = reverse_owner
            .as_ref()
            .map(|c| c.instance_id())
            .unwrap_or("fixture")
            .to_string();
        destination.sql(&format!(
            "UPDATE {schema}.owner SET coordinator={}",
            lit(&coordinator)
        ));
        let key = Key {
            migration: schema.clone(),
            cutover: suffix,
            epoch,
            coordinator,
        };
        let mut target = cutover::pg::Target {
            connection: destination,
            state: destination_state,
            acknowledged_triggers: BTreeSet::new(),
        };
        target.initialize().unwrap();
        Self {
            source: cutover::pg::Source {
                connection: source,
                state,
                drained: DrainCounts::default(),
                pre_fence: || Ok(()),
            },
            target,
            schema,
            installation,
            source_role,
            destination_role,
            slot,
            key,
            epoch,
            reverse_owner,
        }
    }
    fn setup_reverse(&mut self) {
        use skedaddle::coordinator::{Event, State, Transition};
        let owner = self
            .reverse_owner
            .as_mut()
            .expect("logical fixture coordinator");
        let runtime = self.target.connection.runtime.clone();
        runtime.block_on(async {
            for to in [State::Assessed, State::Copying, State::CatchingUp] {
                owner
                    .commit(Transition::Lifecycle {
                        event: Event::Advance { to },
                    })
                    .await
                    .unwrap();
            }
            owner
                .commit(Transition::Lifecycle {
                    event: Event::Readiness {
                        facts: support::ready(),
                    },
                })
                .await
                .unwrap();
            for to in [State::SourceFenced, State::FinalBoundaryApplied] {
                owner
                    .commit(Transition::Lifecycle {
                        event: Event::Advance { to },
                    })
                    .await
                    .unwrap();
            }
        });
        let version = self.target.connection.sql("SHOW server_version_num")[0][0]
            .parse()
            .unwrap();
        let config = skedaddle::pg::reverse::Config::new(
            &self.installation,
            version,
            vec![(self.schema.clone(), "items".into())],
        )
        .unwrap();
        let proof = owner
            .setup_reverse(
                &runtime,
                &config,
                &mut self.target.connection,
                &mut self.source.connection,
                &mut self.target.state,
            )
            .unwrap();
        self.target.state.attach_reverse_proof(proof);
    }
    fn authority(&self) -> PgAuthority {
        PgAuthority {
            pg: self.target.connection.clone(),
            schema: self.schema.clone(),
        }
    }
}
impl Drop for Fixture {
    fn drop(&mut self) {
        // Only this fixture's objects; the databases and other owners survive.
        if self.reverse_owner.is_some() {
            let destination_version = self.target.connection.sql("SHOW server_version_num")[0][0]
                .parse()
                .unwrap();
            let config = skedaddle::pg::reverse::Config::new(
                &self.installation,
                destination_version,
                vec![(self.schema.clone(), "items".into())],
            )
            .unwrap();
            let trigger =
                skedaddle::pg::ddl::TriggerSql::new(&self.installation, destination_version)
                    .unwrap();
            self.target.connection.sql(&format!("{} SELECT pg_drop_replication_slot(slot_name) FROM pg_replication_slots WHERE slot_name={}; DROP PUBLICATION IF EXISTS {};", trigger.remove, lit(&config.slot()), config.publication()));
            self.source.connection.sql(&format!("SELECT pg_replication_origin_drop(roname) FROM pg_replication_origin WHERE roname={}", lit(&config.origin())));
        }
        let source_version = self.source.connection.sql("SHOW server_version_num")[0][0]
            .parse()
            .unwrap();
        let trigger =
            skedaddle::pg::ddl::TriggerSql::new(&self.installation, source_version).unwrap();
        self.source.connection.sql(&trigger.remove);
        if let Some(slot) = &self.slot {
            self.source
                .connection
                .sql(&format!("SELECT pg_drop_replication_slot({})", lit(slot)));
        }
        self.source.connection.sql(&format!("DROP SCHEMA {} CASCADE; DROP ROLE {}; DELETE FROM _skedaddle.cutover_marker WHERE migration={}; DELETE FROM _skedaddle.fence_state WHERE migration={} AND epoch={}; DELETE FROM _skedaddle.authority WHERE migration={} AND epoch={};", self.schema, self.source_role, lit(&self.key.migration), lit(&self.key.migration), self.epoch, lit(&self.key.migration), self.epoch));
        self.target.connection.sql(&format!("DROP SCHEMA {} CASCADE; DROP ROLE {}; DELETE FROM _skedaddle.cutover_activation WHERE migration={};", self.schema, self.destination_role, lit(&self.key.migration)));
    }
}
// Fixture authority uses a real PG owner row and session advisory lock. Production
// ownership/failover and fail-stop transport supervision are supplied by P2.
struct PgAuthority {
    pg: Pg,
    schema: String,
}
impl Authority for PgAuthority {
    fn run<T>(&mut self, key: &Key, run: impl FnOnce() -> Result<T>) -> Result<T> {
        let lock = format!("hashtextextended({},0)", lit(&key.migration));
        self.pg.sql(&format!("SELECT pg_advisory_lock({lock})"));
        let rows = self.pg.sql(&format!(
            "SELECT epoch::text,coordinator FROM {}.owner",
            self.schema
        ));
        let result = if rows[0][0] != key.epoch.to_string() || rows[0][1] != key.coordinator {
            Err(Error::LostOwnership)
        } else {
            run()
        };
        self.pg.sql(&format!("SELECT pg_advisory_unlock({lock})"));
        result
    }
}
struct RealStatus {
    pg: Pg,
    audit: Rc<RefCell<Option<Audit>>>,
}
impl Status for RealStatus {
    fn readiness(&mut self, _: &Key) -> Result<()> {
        assert_eq!(
            self.pg.sql("SELECT pg_is_in_recovery()::text")[0][0],
            "false"
        );
        Ok(())
    }
    fn breached(&mut self, _: &Key) -> Result<bool> {
        Ok(false)
    } // Fixture has no concurrent writer.
    fn now_ms(&mut self) -> Result<u64> {
        Ok(self
            .pg
            .sql("SELECT floor(extract(epoch FROM clock_timestamp())*1000)::bigint::text")[0][0]
            .parse()
            .unwrap())
    }
    fn audit(&mut self, _: &Key, audit: &Audit) -> Result<()> {
        *self.audit.borrow_mut() = Some(audit.clone());
        Ok(())
    }
}
struct MarkerProgress {
    source: Pg,
    destination: Pg,
    slot: String,
    schema: String,
    root: PathBuf,
}
impl Progress for MarkerProgress {
    fn buffered(&mut self, marker: &Marker) -> Result<Option<Marker>> {
        let rows = self.source.sql(&format!("SELECT lsn::text,data FROM pg_logical_slot_peek_changes({},NULL,NULL,'include-xids','0')", lit(&self.slot)));
        let found = rows.iter().any(|r| {
            r[1].contains(&format!(
                "prefix: {},",
                skedaddle::pg::chunk::MESSAGE_PREFIX
            )) && r[1].ends_with(&marker.payload())
                && fence::parse_lsn(&r[0]).unwrap() <= marker.lsn
        });
        if found {
            std::fs::create_dir_all(&self.root).unwrap();
            std::fs::write(
                self.root.join("marker.json"),
                serde_json::to_vec(marker).unwrap(),
            )
            .unwrap();
        }
        Ok(found.then(|| marker.clone()))
    }
    fn applied(&mut self, marker: &Marker) -> Result<Option<Marker>> {
        let buffered: Marker =
            serde_json::from_slice(&std::fs::read(self.root.join("marker.json")).unwrap()).unwrap();
        if &buffered != marker {
            return Ok(None);
        }
        self.destination.sql(&format!(
            "INSERT INTO {}.applied VALUES({},{},{}) ON CONFLICT(cutover) DO NOTHING",
            self.schema,
            lit(&marker.cutover),
            marker.epoch,
            lit(&marker.lsn.to_string())
        ));
        self.source.sql(&format!(
            "SELECT lsn::text FROM pg_logical_slot_get_changes({},NULL,NULL,'include-xids','0')",
            lit(&self.slot)
        ));
        Ok(Some(buffered))
    }
}
struct RealVerifier {
    source: Pg,
    destination: Pg,
    schema: String,
}
impl Verifier for RealVerifier {
    fn boundary(&mut self, marker: &Marker) -> Result<VerifiedBoundary> {
        let sql = format!("SELECT id::text,v FROM {}.items ORDER BY id", self.schema);
        let source = self.source.sql(&sql);
        let destination = self.destination.sql(&sql);
        let receipt = self.destination.sql(&format!(
            "SELECT epoch::text,lsn FROM {}.applied WHERE cutover={}",
            self.schema,
            lit(&marker.cutover)
        ));
        assert_eq!(
            receipt,
            vec![vec![marker.epoch.to_string(), marker.lsn.to_string()]]
        );
        let total = source.len() as u64;
        let equal = source == destination;
        Ok(VerifiedBoundary {
            marker: marker.clone(),
            coverage: skedaddle::verify::Coverage {
                total,
                verified: if equal { total } else { 0 },
                mismatched: if equal { 0 } else { total },
                ..Default::default()
            }
            .into(),
        })
    }
}
struct ReverseNotConfigured;
impl Reverse for ReverseNotConfigured {
    fn confirm(&mut self, _: &Key, _: &Marker) -> Result<()> {
        // Explicit fixture attestation only. P11 provides the production implementation.
        Ok(())
    }
}

#[test]
fn restore_without_journaled_reverse_proof_keeps_destination_fenced() {
    let Some(urls) = gated("restore_without_journaled_reverse_proof_keeps_destination_fenced")
    else {
        return;
    };
    let _serial = SERIAL.lock().unwrap();
    let mut f = Fixture::new(urls, false);
    // The real source and destination are fenced before the Restore boundary.
    f.source.fence(&f.key, &mut |_| Ok(())).unwrap();
    let marker = f.source.final_marker(&f.key).unwrap();
    f.target
        .state
        .begin_activation(marker.payload(), BTreeSet::new(), &mut |_| Ok(()))
        .unwrap();
    f.target
        .state
        .execute_next(&mut f.target.connection, &mut |_| Ok(()))
        .unwrap();
    assert_eq!(f.target.state.next, activate::Step::Restore);
    let mut authorized = false;
    let error = f
        .target
        .activate(&f.key, &marker, &mut |_| Ok(()), &mut || {
            authorized = true;
            Ok(())
        })
        .unwrap_err();
    assert_eq!(
        error,
        Error::ReverseProof(skedaddle::coordinator::reverse::ProofError::Missing)
    );
    assert!(
        error
            .to_string()
            .ends_with(skedaddle::coordinator::reverse::NEXT_STEP)
    );
    assert!(!authorized);
    assert_eq!(f.target.state.next, activate::Step::Restore);
    assert_eq!(f.target.activated(&f.key).unwrap(), None);
    assert_eq!(
        f.target.connection.sql(&format!(
            "SELECT rolcanlogin::text FROM pg_roles WHERE rolname={}",
            lit(&f.destination_role)
        ))[0][0],
        "false"
    );
}

#[test]
fn abort_before_activation_restores_source() {
    let Some(urls) = gated("abort_before_activation_restores_source") else {
        return;
    };
    let _serial = SERIAL.lock().unwrap();
    let mut f = Fixture::new(urls, false);
    // Ensure the marker receipt relation exists for fixture cleanup, without
    // emitting a marker on this pre-activation abort path.
    f.source.connection.sql("CREATE SCHEMA IF NOT EXISTS _skedaddle; CREATE TABLE IF NOT EXISTS _skedaddle.cutover_marker(migration text PRIMARY KEY,cutover text NOT NULL,epoch bigint NOT NULL,lsn pg_lsn NOT NULL)");
    let mut state = State::new(f.key.clone()).unwrap();
    let mut authority = f.authority();
    let mut status = RealStatus {
        pg: f.target.connection.clone(),
        audit: Rc::new(RefCell::new(None)),
    };
    let mut progress = MarkerProgress {
        source: f.source.connection.clone(),
        destination: f.target.connection.clone(),
        slot: String::new(),
        schema: f.schema.clone(),
        root: PathBuf::new(),
    };
    let mut verifier = RealVerifier {
        source: f.source.connection.clone(),
        destination: f.target.connection.clone(),
        schema: f.schema.clone(),
    };
    let mut sequences = cutover::pg::SequenceSync {
        source: f.source.connection.clone(),
        destination: f.target.connection.clone(),
        scope: activate::SequenceScope {
            tables: f.source.state.config.tables.clone(),
            sequences: vec![],
        },
        timeout_ms: 10_000,
    };
    let mut reverse = ReverseNotConfigured;
    while state.next != Step::FinalMarker {
        state
            .execute_next(
                &mut authority,
                &mut Components {
                    source: &mut f.source,
                    destination: &mut f.target,
                    progress: &mut progress,
                    verifier: &mut verifier,
                    sequences: &mut sequences,
                    reverse: &mut reverse,
                    status: &mut status,
                },
                &mut |_| Ok(()),
            )
            .unwrap();
    }
    // Live roles/ACLs deliberately fail the proof; source must stay NOLOGIN.
    f.target
        .connection
        .sql(&format!("ALTER ROLE {} LOGIN", f.destination_role));
    assert!(
        state
            .abort(
                &mut f.authority(),
                &mut f.source,
                &mut f.target,
                &mut |_| Ok(())
            )
            .is_err()
    );
    assert_eq!(
        f.source.connection.sql(&format!(
            "SELECT rolcanlogin::text FROM pg_roles WHERE rolname={}",
            lit(&f.source_role)
        ))[0][0],
        "false"
    );
    f.target
        .connection
        .sql(&format!("ALTER ROLE {} NOLOGIN", f.destination_role));
    state
        .abort(
            &mut f.authority(),
            &mut f.source,
            &mut f.target,
            &mut |_| Ok(()),
        )
        .unwrap();
    assert_eq!(state.next, Step::Aborted);
    f.source.connection.sql(&format!(
        "BEGIN; SET LOCAL ROLE {}; INSERT INTO {}.items(v) VALUES('restored'); COMMIT",
        f.source_role, f.schema
    ));
    assert_eq!(
        f.source
            .connection
            .sql(&format!("SELECT count(*)::text FROM {}.items", f.schema))[0][0],
        "2"
    );
}

#[test]
fn measured_interruption_reported() {
    let Some(urls) = gated("measured_interruption_reported") else {
        return;
    };
    let _serial = SERIAL.lock().unwrap();
    let root = PathBuf::from(
        std::env::var_os("SKEDADDLE_TEST_ROOT")
            .expect("set SKEDADDLE_TEST_ROOT under J:/gigglesdb-work"),
    );
    assert!(root.starts_with("J:/gigglesdb-work"));
    let mut f = Fixture::new(urls, true);
    let mut state = State::new(f.key.clone()).unwrap();
    let audit = Rc::new(RefCell::new(None));
    let mut status = RealStatus {
        pg: f.target.connection.clone(),
        audit: audit.clone(),
    };
    let mut progress = MarkerProgress {
        source: f.source.connection.clone(),
        destination: f.target.connection.clone(),
        slot: f.slot.clone().unwrap(),
        schema: f.schema.clone(),
        root: root.join(&f.schema),
    };
    let mut verifier = RealVerifier {
        source: f.source.connection.clone(),
        destination: f.target.connection.clone(),
        schema: f.schema.clone(),
    };
    let mut sequences = cutover::pg::SequenceSync {
        source: f.source.connection.clone(),
        destination: f.target.connection.clone(),
        scope: activate::SequenceScope {
            tables: f.source.state.config.tables.clone(),
            sequences: vec![],
        },
        timeout_ms: 10_000,
    };
    let mut authority = f.authority();
    let mut reverse = ReverseNotConfigured;
    let mut journal = Vec::new();
    for _ in 0..30 {
        if state.next == Step::Complete {
            break;
        }
        if state.next == Step::Reverse {
            f.setup_reverse();
        }
        if state.next == Step::Activate {
            let retained = f.target.state.clone();
            let marker = state.marker.as_ref().unwrap();
            let mut stale = f.key.clone();
            stale.epoch += 1;
            let mut authorized = false;
            assert_eq!(
                f.target.activate(&stale, marker, &mut |_| Ok(()), &mut || {
                    authorized = true;
                    Ok(())
                }),
                Err(Error::ReverseProof(
                    skedaddle::coordinator::reverse::ProofError::Mismatch
                ))
            );
            assert!(!authorized);
            f.target.state = retained.clone();
            f.target.state.evidence[0]
                .observed_at
                .push_str("-different-fence");
            assert_eq!(
                f.target.activate(&f.key, marker, &mut |_| Ok(()), &mut || {
                    authorized = true;
                    Ok(())
                }),
                Err(Error::ReverseProof(
                    skedaddle::coordinator::reverse::ProofError::Mismatch
                ))
            );
            assert!(!authorized);
            f.target.state = retained;
        }
        let result = state.execute_next(
            &mut authority,
            &mut Components {
                source: &mut f.source,
                destination: &mut f.target,
                progress: &mut progress,
                verifier: &mut verifier,
                sequences: &mut sequences,
                reverse: &mut reverse,
                status: &mut status,
            },
            &mut |r| {
                journal.push(serde_json::to_string(r).unwrap());
                Ok(())
            },
        );
        if result == Err(Error::Pending) {
            std::thread::sleep(Duration::from_millis(20));
        } else {
            result.unwrap();
        }
    }
    assert_eq!(state.next, Step::Complete);
    let receipt = f.target.activation_receipt(&f.key).unwrap().unwrap();
    assert_eq!(receipt.migration, f.key.migration);
    assert_eq!(receipt.cutover, f.key.cutover);
    assert_eq!(receipt.fence_epoch, f.key.epoch as u64);
    assert_eq!(receipt.fence_owner, f.key.coordinator);
    let identity = f
        .target
        .connection
        .sql("SELECT system_identifier::text,current_database() FROM pg_control_system()");
    assert_eq!(receipt.destination.system_identifier, identity[0][0]);
    assert_eq!(receipt.destination.database, identity[0][1]);
    let report = audit.borrow().clone().unwrap();
    assert_eq!(&report, state.audit.as_ref().unwrap());
    assert_eq!(receipt.activated_at_ms, report.activated_at_ms);
    assert_eq!(
        report.write_pause_ms,
        report.activated_at_ms - report.fence_start_ms
    );
    assert!(report.fence_end_ms >= report.fence_start_ms);
    assert!(report.final_lsn > 0);
    assert!(report.write_pause_ms > 0);
    assert_eq!(report.coverage.verified, 1);
    eprintln!(
        "measured cutover write pause: {} ms; F={}; drained={:?}",
        report.write_pause_ms, report.final_lsn, report.drained
    );
    std::fs::write(progress.root.join("journal.jsonl"), journal.join("\n")).unwrap();
    f.target.connection.sql(&format!(
        "BEGIN; SET LOCAL ROLE {}; INSERT INTO {}.items(v) VALUES('activated'); COMMIT",
        f.destination_role, f.schema
    ));
    assert_eq!(
        state.abort(
            &mut authority,
            &mut f.source,
            &mut f.target,
            &mut |_| Ok(())
        ),
        Err(Error::UseRollback)
    );
}

// The harness CA is explicit; missing trust is a failure once a DB gate is set.
fn tls_config(postgres: tokio_postgres::Config) -> skedaddle::pg::tls::Config {
    let path = std::env::var_os("SKEDADDLE_TEST_CONFIG").expect("TLS harness config required");
    let config: serde_json::Value =
        serde_json::from_slice(&std::fs::read(path).expect("read TLS harness config"))
            .expect("TLS harness JSON");
    let ca_pem = config["ca_pem"]
        .as_str()
        .or_else(|| config["replication"]["ca_pem"].as_str())
        .expect("harness ca_pem or replication.ca_pem required");
    skedaddle::pg::tls::Config::new(postgres, ca_pem)
}

async fn tls_connect(
    dsn: &str,
) -> std::result::Result<
    (tokio_postgres::Client, skedaddle::pg::tls::Driver),
    skedaddle::pg::tls::Error,
> {
    let config = tls_config(dsn.parse().expect("harness PostgreSQL configuration"));
    let (client, driver, transport) =
        skedaddle::pg::tls::connect(&config, &skedaddle::security::TlsPolicy::Required).await?;
    assert!(transport.encrypted());
    assert!(transport.warnings.is_empty());
    Ok((client, driver))
}
