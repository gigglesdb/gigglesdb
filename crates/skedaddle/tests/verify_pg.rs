#[tokio::test]
async fn range_caps_split_without_returning_partial_rows_and_record_source_lsn() {
    let Some(f) =
        Fixture::new("range_caps_split_without_returning_partial_rows_and_record_source_lsn").await
    else {
        return;
    };
    let projection = Projection::new(vec!["amount".into()]).unwrap();
    // Keep setup writes off the verifier's independent read-only connection.
    let setup = setup_connection(&f.source_dsn).await;
    // Huge excluded columns must neither be read nor count against the cap.
    setup
        .batch_execute(&format!(
            "UPDATE {}.items SET excluded=repeat('x',100000)",
            f.schema
        ))
        .await
        .unwrap();
    let mut source = f.reader(Side::Source, 3, 57).await;
    let read = source.read_with_lsn(&f.range(), &projection).await.unwrap();
    assert_eq!(read.rows.len(), 3);
    assert!(read.lsn > 0);
    assert!(
        source
            .fetch(
                &f.range(),
                &Projection::new(vec!["excluded".into()]).unwrap()
            )
            .await
            .is_err()
    );
    for (rows, bytes) in [(2, 4096), (3, 56)] {
        let mut source = f.reader(Side::Source, rows, bytes).await;
        let Err(VerifyError::SplitRequired(split)) = source.fetch(&f.range(), &projection).await
        else {
            panic!("split required");
        };
        assert_eq!(split[0].hi, Some(vec![Value::Int8(2)]));
        assert_eq!(split[0].hi, split[1].lo);
        assert_eq!(source.fetch(&split[0], &projection).await.unwrap().len(), 1);
        assert_eq!(source.fetch(&split[1], &projection).await.unwrap().len(), 2);
    }
    setup
        .batch_execute(&format!(
            "INSERT INTO {}.items (id,amount) VALUES (10,100)",
            f.schema
        ))
        .await
        .unwrap();
    let rows = f
        .reader(Side::Source, 4, 4096)
        .await
        .fetch(&f.range(), &projection)
        .await
        .unwrap();
    assert_eq!(
        rows.iter().map(|r| r.key.clone()).collect::<Vec<_>>(),
        vec![
            vec![Value::Int8(1)],
            vec![Value::Int8(2)],
            vec![Value::Int8(3)],
            vec![Value::Int8(10)]
        ]
    );
    f.cleanup().await;
}

#[tokio::test]
async fn destination_fk_integrity_pages_not_valid_constraints() {
    let Some(f) = Fixture::new("destination_fk_integrity_pages_not_valid_constraints").await else {
        return;
    };
    f.corrupt("CREATE TABLE {table}_parent (amount bigint PRIMARY KEY); INSERT INTO {table}_parent VALUES (10),(30); ALTER TABLE {table} ADD CONSTRAINT amount_fk FOREIGN KEY (amount) REFERENCES {table}_parent(amount) NOT VALID").await;
    let mut destination = f.reader(Side::Destination, 3, 4096).await;
    let findings = destination.check_foreign_keys(1).await.unwrap();
    assert_eq!(findings.len(), 1);
    assert_eq!(findings[0].violating_rows, 1);
    let mut source = f.reader(Side::Source, 3, 4096).await;
    assert!(source.check_foreign_keys(1).await.is_err());
    f.cleanup().await;
}

// The harness CA is explicit; missing trust is a failure once a DB gate is set.
fn tls_config(postgres: tokio_postgres::Config) -> skedaddle::pg::tls::Config {
    let path = std::env::var_os("SKEDADDLE_TEST_CONFIG").expect("TLS harness config required");
    let config: serde_json::Value =
        serde_json::from_slice(&std::fs::read(path).expect("read TLS harness config"))
            .expect("TLS harness JSON");
    let ca_pem = config["ca_pem"]
        .as_str()
        .or_else(|| config["replication"]["ca_pem"].as_str())
        .expect("harness ca_pem or replication.ca_pem required");
    skedaddle::pg::tls::Config::new(postgres, ca_pem)
}

async fn tls_connect(
    dsn: &str,
) -> std::result::Result<
    (tokio_postgres::Client, skedaddle::pg::tls::Driver),
    skedaddle::pg::tls::Error,
> {
    let config = tls_config(dsn.parse().expect("harness PostgreSQL configuration"));
    let (client, driver, transport) =
        skedaddle::pg::tls::connect(&config, &skedaddle::security::TlsPolicy::Required).await?;
    assert!(transport.encrypted());
    assert!(transport.warnings.is_empty());
    Ok((client, driver))
}
