#[tokio::test]
async fn detects_single_column_corruption() {
    let Some(f) = Fixture::new("detects_single_column_corruption").await else {
        return;
    };
    f.corrupt("UPDATE {table} SET amount=99 WHERE id=2").await;
    let result = f.comparison().await;
    let [Difference::Changed { key, columns }] = result.differences.as_slice() else {
        panic!("one changed row expected");
    };
    assert_eq!(*key, vec![Value::Int8(2)]);
    assert_eq!(columns.len(), 1);
    assert_eq!(columns[0].column, "amount");
    assert_eq!(columns[0].destination, Value::Int8(99));
    f.cleanup().await;
}

#[tokio::test]
async fn detects_sequence_behind() {
    let Some(f) = Fixture::new("detects_sequence_behind").await else {
        return;
    };
    f.source
        .batch_execute(&format!(
            "SELECT setval('{}.items_id_seq',100,true)",
            f.schema
        ))
        .await
        .unwrap();
    f.corrupt("SELECT setval(pg_get_serial_sequence('{table}','id'),10,true)")
        .await;
    let source = f
        .reader(Side::Source, 10, 4096)
        .await
        .collect_sections()
        .await
        .unwrap();
    let destination = f
        .reader(Side::Destination, 10, 4096)
        .await
        .collect_sections()
        .await
        .unwrap();
    let diff = diff_sections(&source, &destination);
    assert_eq!(diff.sequences.len(), 1);
    assert!(diff.sequences[0].detail.contains("behind"));
    f.cleanup().await;
}

