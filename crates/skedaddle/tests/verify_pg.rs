//! Real PostgreSQL qualification; plain cargo runs print an explicit harness skip.
use std::{
    cmp::Ordering,
    sync::atomic::{AtomicU64, Ordering as AtomicOrdering},
};

use skedaddle::{
    mapping::{PgType, Value},
    pg::chunk::{ChunkId, Direction, KeyColumn, QualifiedName, TableKey},
    verify::{
        Difference, Key, KeyOrder, Projection, RangePlan, Result, RowSource, VerifyError,
        compare_sources,
        sql::{Column, PgRowSource, RangeBudget, Side, diff_sections},
    },
};
use tokio_postgres::Client;

struct IntOrder;
impl KeyOrder for IntOrder {
    fn compare_keys(&self, left: &Key, right: &Key) -> Result<Ordering> {
        match (left.as_slice(), right.as_slice()) {
            ([Value::Int8(a)], [Value::Int8(b)]) => Ok(a.cmp(b)),
            _ => Err(VerifyError::Invalid("test key type")),
        }
    }
}

/// Accept harness DSNs whether stored directly or inside a named endpoint.
/// Endpoint variables are useful for an already running, externally owned pair.
fn endpoint(config: &serde_json::Value, side: &str) -> Option<String> {
    fn walk(value: &serde_json::Value, path: &str, side: &str) -> Option<String> {
        match value {
            serde_json::Value::String(s)
                if path.contains(side)
                    && (s.starts_with("postgres://")
                        || s.starts_with("postgresql://")
                        || s.contains("host=")) =>
            {
                Some(s.clone())
            }
            serde_json::Value::Object(map) => map
                .iter()
                .find_map(|(k, v)| walk(v, &format!("{path}.{}", k.to_lowercase()), side)),
            _ => None,
        }
    }
    walk(config, "", side)
}

fn harness(test: &str) -> Option<(String, String)> {
    let Some(path) = std::env::var_os("SKEDADDLE_TEST_CONFIG") else {
        use std::io::Write;
        let _ = writeln!(
            std::io::stderr(),
            "SKIP {test}: real PostgreSQL harness required; SKEDADDLE_TEST_CONFIG is unset (no DB assertions ran)"
        );
        return None;
    };
    let config: serde_json::Value =
        serde_json::from_slice(&std::fs::read(path).expect("read harness config"))
            .expect("harness JSON");
    let source = std::env::var("SKEDADDLE_VERIFY_SOURCE_URL")
        .ok()
        .or_else(|| endpoint(&config, "source"))
        .expect("harness source DSN or SKEDADDLE_VERIFY_SOURCE_URL");
    let destination = std::env::var("SKEDADDLE_VERIFY_DESTINATION_URL")
        .ok()
        .or_else(|| endpoint(&config, "destination"))
        .expect("harness destination DSN or SKEDADDLE_VERIFY_DESTINATION_URL");
    Some((source, destination))
}

// Setup writes use separate clients; PgRowSource owns every read-only verifier session.
async fn setup_connection(dsn: &str) -> Client {
    let (client, connection) = tls_connect(dsn).await.expect("test PostgreSQL connection");
    tokio::spawn(async move {
        connection.await.expect("test PostgreSQL driver");
    });
    client
}

struct Fixture {
    source_dsn: String,
    destination_dsn: String,
    source: Client,
    destination: Client,
    schema: String,
}
impl Fixture {
    async fn new(test: &str) -> Option<Self> {
        static NEXT: AtomicU64 = AtomicU64::new(0);
        let (source_dsn, destination_dsn) = harness(test)?;
        let schema = format!(
            "verify_p8b_{}_{}_{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos(),
            NEXT.fetch_add(1, AtomicOrdering::Relaxed)
        );
        let source = setup_connection(&source_dsn).await;
        let destination = setup_connection(&destination_dsn).await;
        let ddl = format!(
            "CREATE SCHEMA {schema}; CREATE TABLE {schema}.items (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, amount bigint NOT NULL DEFAULT 0, excluded text); INSERT INTO {schema}.items (id,amount) VALUES (1,10),(2,20),(3,30)"
        );
        source.batch_execute(&ddl).await.expect("source fixture");
        destination
            .batch_execute(&ddl)
            .await
            .expect("destination fixture");
        Some(Self {
            source_dsn,
            destination_dsn,
            source,
            destination,
            schema,
        })
    }
    fn key(&self) -> TableKey {
        TableKey {
            table: format!("{}.items", self.schema),
            relation: QualifiedName {
                schema: self.schema.clone(),
                name: "items".into(),
            },
            columns: vec![KeyColumn {
                name: "id".into(),
                pg_type: PgType::Int8,
                sql_type: QualifiedName {
                    schema: "pg_catalog".into(),
                    name: "int8".into(),
                },
                collation: None,
                direction: Direction::Asc,
            }],
        }
    }
    fn range(&self) -> RangePlan {
        RangePlan {
            id: ChunkId {
                table: self.key().table,
                plan: "a".repeat(64),
                ordinal: 0,
            },
            lo: None,
            hi: None,
        }
    }
    async fn reader(&self, side: Side, max_rows: u64, max_bytes: u64) -> PgRowSource<IntOrder> {
        let dsn = if side == Side::Source {
            &self.source_dsn
        } else {
            &self.destination_dsn
        };
        let reader = PgRowSource::connect(
            &tls_config(dsn.parse().expect("verifier PostgreSQL configuration")),
            side,
            self.key(),
            vec![Column {
                name: "amount".into(),
                pg_type: PgType::Int8,
            }],
            IntOrder,
            RangeBudget {
                max_rows,
                max_bytes,
            },
        )
        .await
        .unwrap();
        assert!(reader.transport_evidence().encrypted());
        reader
    }
    async fn corrupt(&self, sql: &str) {
        self.destination
            .batch_execute(&sql.replace("{table}", &format!("{}.items", self.schema)))
            .await
            .expect("seed destination SQL corruption");
    }
    async fn comparison(&self) -> skedaddle::verify::Comparison {
        let mut source = self.reader(Side::Source, 10, 4096).await;
        let mut destination = self.reader(Side::Destination, 10, 4096).await;
        compare_sources(
            &mut source,
            &mut destination,
            &self.range(),
            &Projection::new(vec!["amount".into()]).unwrap(),
        )
        .await
        .unwrap()
    }
    async fn cleanup(self) {
        let sql = format!("DROP SCHEMA {} CASCADE", self.schema);
        self.source.batch_execute(&sql).await.unwrap();
        self.destination.batch_execute(&sql).await.unwrap();
    }
}

#[tokio::test]
async fn detects_missing_row() {
    let Some(f) = Fixture::new("detects_missing_row").await else {
        return;
    };
    f.corrupt("DELETE FROM {table} WHERE id=2").await;
    assert_eq!(
        f.comparison().await.differences,
        vec![Difference::Missing {
            key: vec![Value::Int8(2)]
        }]
    );
    f.cleanup().await;
}

