#!/usr/bin/env bash
set -euo pipefail
# Requires curl and Python 3; the fresh compose project owns all resources.
base=${NUNYA_SPANNER_REST:-http://127.0.0.1:9020}/v1
project=projects/test-project
instance=$project/instances/test-instance
json() { python -c 'import json,sys; print(json.dumps(sys.argv[1]))' "$1"; }
post() { curl --fail --silent --show-error -H 'Content-Type: application/json' -d "$2" "$base/$1"; }
wait_operation() {
  local response=$1 name done
  name=$(printf '%s' "$response" | python -c 'import json,sys; print(json.load(sys.stdin).get("name",""))')
  for ((attempt=0; attempt<120; attempt++)); do
    done=$(printf '%s' "$response" | python -c 'import json,sys; x=json.load(sys.stdin); assert "error" not in x, "operation failed"; print(x.get("done",False))')
    [[ $done == True ]] && return
    [[ -n $name ]] || { echo 'missing operation name' >&2; return 1; }
    sleep 1
    response=$(curl --fail --silent --show-error "$base/$name")
  done
  echo 'operation timed out' >&2; return 1
}
for ((attempt=0; attempt<120; attempt++)); do
  if curl --fail --silent "$base/$project/instanceConfigs" >/dev/null; then break; fi
  sleep 1
done
wait_operation "$(post "$project/instances" '{"instanceId":"test-instance","instance":{"config":"projects/test-project/instanceConfigs/emulator-config","displayName":"Nunya harness","nodeCount":1}}')"
for dialect in gsql pgdb; do
  if [[ $dialect == gsql ]]; then
    ddl='["CREATE TABLE Customers (Id INT64 NOT NULL, Email STRING(MAX), Country STRING(MAX), Phone STRING(MAX), FailedPayments INT64) PRIMARY KEY(Id)","CREATE TABLE Outbox (Id INT64 NOT NULL, ToAddress STRING(MAX), Template STRING(MAX)) PRIMARY KEY(Id)","CREATE TABLE Notes (Id INT64 NOT NULL, Body STRING(MAX)) PRIMARY KEY(Id)"]'
    request='{"createStatement":"CREATE DATABASE gsql","extraStatements":'"$ddl"'}'
  else
    # Lowercase unquoted identifiers mirror the PostgreSQL worked example.
    ddl='["CREATE TABLE customers (id bigint PRIMARY KEY, email varchar, country varchar, phone varchar, failed_payments bigint)","CREATE TABLE outbox (id bigint GENERATED BY DEFAULT AS IDENTITY (BIT_REVERSED_POSITIVE) PRIMARY KEY, to_address varchar, template varchar)","CREATE TABLE notes (id bigint PRIMARY KEY, body varchar)"]'
    request='{"createStatement":"CREATE DATABASE pgdb","databaseDialect":"POSTGRESQL"}'
  fi
  wait_operation "$(post "$instance/databases" "$request")"
  db=$instance/databases/$dialect
  if [[ $dialect == pgdb ]]; then wait_operation "$(curl --fail --silent --show-error -X PATCH -H 'Content-Type: application/json' -d '{"statements":'"$ddl"'}' "$base/$db/ddl")"; fi
  session=$(post "$db/sessions" '{}' | python -c 'import json,sys; print(json.load(sys.stdin)["name"])')
  tx=$(post "$session:beginTransaction" '{"options":{"readWrite":{}}}' | python -c 'import json,sys; print(json.load(sys.stdin)["id"])')
  # GoogleSQL requires an explicit INSERT column list.
  if [[ $dialect == gsql ]]; then table='Customers (Id, Email, Country, Phone, FailedPayments)'; else table='customers (id, email, country, phone, failed_payments)'; fi
  sql="INSERT INTO $table VALUES (1,'alice@example.test','US','555-0101',0),(2,'bob@example.test','GB','555-0102',1),(3,'carol@example.test','US','555-0103',2),(4,'dave@example.test','CA','555-0104',0),(5,'eve@example.test','GB','555-0105',3)"
  post "$session:executeSql" '{"sql":'"$(json "$sql")"',"transaction":{"id":'"$(json "$tx")"'},"seqno":"1"}' >/dev/null
  post "$session:commit" '{"transactionId":'"$(json "$tx")"'}' >/dev/null
  curl --fail --silent --show-error -X DELETE "$base/$session" >/dev/null
  printf '%s\n' "$db"
done
