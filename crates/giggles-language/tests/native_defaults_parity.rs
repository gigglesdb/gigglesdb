use giggles_core::{
    Admin, CoreError, Engine as StorageEngine, Limits,
    relational::{SqlError, StatementClock, with_sql_parser_forbidden},
};
use giggles_language::{Bindings, Engine, Error, LanguageVersion, SqlRow, Value};
use std::{
    path::PathBuf,
    sync::atomic::{AtomicU64, Ordering},
};

struct Database(PathBuf);
impl Database {
    fn fresh(backend: StorageEngine) -> (Self, Admin, Engine) {
        static NEXT: AtomicU64 = AtomicU64::new(0);
        let path = std::env::temp_dir().join(format!(
            "native-defaults-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        let admin = Admin::create_engine(&path, Limits::default(), backend).unwrap();
        let engine = Engine::with_version(admin.clone(), LanguageVersion::Embedded010);
        (Self(path), admin, engine)
    }
}
impl Drop for Database {
    fn drop(&mut self) {
        if self.0.is_dir() {
            std::fs::remove_dir_all(&self.0).unwrap();
        } else {
            std::fs::remove_file(&self.0).unwrap();
        }
    }
}
fn backends() -> Vec<StorageEngine> {
    let mut backends = vec![StorageEngine::Legacy];
    if cfg!(feature = "engine-rocksdb") {
        backends.push(StorageEngine::V2);
    }
    backends
}
fn clock() -> StatementClock {
    StatementClock {
        unavailable: None,
        transaction_us: 0,
        statement_us: 0,
        zone: None,
        wall: None,
    }
}
fn values(rows: Vec<SqlRow>) -> Vec<Vec<Value>> {
    rows.into_iter().map(|r| r.values).collect()
}
struct Pair {
    engine: Engine,
    left: Admin,
    right: Admin,
    _paths: [Database; 2],
}
impl Pair {
    fn new(backend: StorageEngine, definition: &str) -> Self {
        let (l, left, engine) = Database::fresh(backend);
        let (r, right, _) = Database::fresh(backend);
        let ddl = format!("create table items(id bigint primary key,{definition})");
        for admin in [&left, &right] {
            admin.sql_session().execute(&ddl, &[], None).unwrap();
        }
        Self {
            engine,
            left,
            right,
            _paths: [l, r],
        }
    }
    fn insert(&self, native: &str, sql: &str) {
        let Self {
            engine,
            left,
            right,
            ..
        } = self;
        let actual =
            with_sql_parser_forbidden(|| engine.execute_text(native, &Bindings::new()))
                .unwrap_or_else(|error| panic!("{native}: {error:?}"));
        let expected = right
            .sql_session()
            .execute_at(sql, &[], None, &clock())
            .unwrap();
        assert_eq!(actual.affected as u64, expected.affected, "{native}");
        assert_eq!(actual.columns, expected.columns, "{native}");
        assert_eq!(values(actual.rows), values(expected.rows), "{native}");
        let query = "select * from items order by id limit 1024";
        assert_eq!(
            values(left.sql_session().execute(query, &[], None).unwrap().rows),
            values(right.sql_session().execute(query, &[], None).unwrap().rows)
        );
    }
}
fn same_error(actual: Error, expected: CoreError) {
    assert_eq!(actual.sqlstate(), Some(giggles_core::sqlstate(&expected)));
}

#[test]
fn omitted_defaults_and_returning_match_sql() {
    for backend in backends() {
        for definition in [
            "v bigint default 7",
            "v bigint not null default 7",
            "v bigint default (-7)::bigint",
            "v bigint default null",
            "v bigserial",
            "v bigint generated by default as identity",
            "v bigint generated always as identity",
        ] {
            let pair = Pair::new(backend, definition);
            pair.insert(
                "insert items set id=1 return *",
                "insert into items(id) values(1) returning *",
            );
            pair.insert(
                "insert into items(id) values(1+1) return id,v,v+1 as successor",
                "insert into items(id) values(2) returning id,v,v+1 as successor",
            );
            pair.insert(
                "insert many into items(id) values(3),(4) at most 2 return *",
                "insert into items(id) values(3),(4) returning *",
            );
            pair.insert(
                "insert into items(id) values(5) on conflict(id) do nothing return *",
                "insert into items(id) values(5) on conflict(id) do nothing returning *",
            );
            pair.insert(
                "insert into items(id) values(5) on conflict(id) do nothing return *",
                "insert into items(id) values(5) on conflict(id) do nothing returning *",
            );
            pair.insert(
                "insert items set id=6 return *",
                "insert into items(id) values(6) returning *",
            );
        }
    }
}

#[test]
fn omitted_required_and_explicit_always_errors_match_sql() {
    for backend in backends() {
        for (definition, native, sql, error) in [
            (
                "v bigint",
                "insert items set v=1",
                "insert into items(v) values(1)",
                SqlError::Null,
            ),
            (
                "v bigint not null",
                "insert items set id=1",
                "insert into items(id) values(1)",
                SqlError::Null,
            ),
            (
                "v bigint generated always as identity",
                "insert items set id=1,v=99",
                "insert into items(id,v) values(1,99)",
                SqlError::GeneratedAlways,
            ),
            (
                "v bigint generated always as identity",
                "insert items set id=1,v=null",
                "insert into items(id,v) values(1,null)",
                SqlError::GeneratedAlways,
            ),
        ] {
            let pair = Pair::new(backend, definition);
            let actual =
                with_sql_parser_forbidden(|| pair.engine.execute_text(native, &Bindings::new()))
                    .unwrap_err();
            let expected = pair
                .right
                .sql_session()
                .execute_at(sql, &[], None, &clock())
                .unwrap_err();
            assert_eq!(expected, CoreError::Sql(error));
            same_error(actual, expected);
        }
    }
}

#[test]
fn rolled_back_sequence_consumption_matches_sql() {
    for backend in backends() {
        for definition in [
            "v bigserial",
            "v bigint generated by default as identity",
            "v bigint generated always as identity",
        ] {
            let pair = Pair::new(backend, definition);
            assert_eq!(
                with_sql_parser_forbidden(|| pair.engine.execute_transaction_text(
                    "transaction { insert items set id=1; require false }",
                    &Bindings::new()
                ))
                .unwrap_err(),
                Error::RequirementFailed
            );
            let mut session = pair.right.sql_session();
            session.execute_at("begin", &[], None, &clock()).unwrap();
            session
                .execute_at("insert into items(id) values(1)", &[], None, &clock())
                .unwrap();
            session.execute_at("rollback", &[], None, &clock()).unwrap();
            drop(session);
            pair.insert(
                "insert items set id=2 return *",
                "insert into items(id) values(2) returning *",
            );
            assert_eq!(
                values(
                    pair.left
                        .sql_session()
                        .execute("select v from items where id=2", &[], None)
                        .unwrap()
                        .rows
                ),
                vec![vec![Value::Int(2)]]
            );
        }
    }
}
