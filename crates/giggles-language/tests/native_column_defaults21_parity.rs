use giggles_core::{Admin, Engine as Storage, Limits};
use giggles_core::relational::with_sql_parser_forbidden as trap;
use giggles_language::*;
use std::{path::PathBuf, sync::atomic::{AtomicU64, Ordering}};
const V: LanguageVersion = LanguageVersion::Embedded021;
struct Db(PathBuf);
impl Db {
    fn fresh(storage: Storage) -> (Self, Admin) {
        static NEXT: AtomicU64 = AtomicU64::new(0);
        let path = std::env::temp_dir().join(format!("column-defaults21-{}-{}", std::process::id(), NEXT.fetch_add(1, Ordering::Relaxed)));
        let admin = Admin::create_engine(&path, Limits::default(), storage).unwrap();
        (Self(path), admin)
    }
}
impl Drop for Db { fn drop(&mut self) { std::fs::remove_dir_all(&self.0).unwrap(); } }
fn storages() -> Vec<Storage> { vec![Storage::Legacy, #[cfg(feature = "engine-rocksdb")] Storage::V2] }
// Independent database storage versions are not logical row data.
fn values(rows: Vec<SqlRow>) -> Vec<Vec<Value>> { rows.into_iter().map(|r| r.values).collect() }
fn snapshot(a: &Admin) -> String {
    let mut m = a.sql_session().catalog_metadata().unwrap(); m.presentation.epoch = 0;
    format!("{:?}", (&m.tables, &m.indexes, &m.presentation))
}
#[test]
fn defaults_identity_serial_match_sql() {
    for storage in storages() {
        let (_l, left) = Db::fresh(storage); let (_r, right) = Db::fresh(storage);
        let engine = Engine::with_version(right.clone(), V); let mut sql = left.sql_session();
        let clock = giggles_core::relational::StatementClock { unavailable: None, transaction_us: 1_000_000, statement_us: 1_000_000, zone: None, wall: None };
        let cases = [
            ("t", "id serial, code int64 default 7, name nullable text default 'x', price numeric default 1.5, flag bool default true, neg int32 default -3", "id SERIAL, code BIGINT NOT NULL DEFAULT 7, name TEXT DEFAULT 'x', price NUMERIC NOT NULL DEFAULT 1.5, flag BOOLEAN NOT NULL DEFAULT true, neg INTEGER NOT NULL DEFAULT -3"),
            ("a", "id int64 generated always as identity, code int64 default 7", "id BIGINT GENERATED ALWAYS AS IDENTITY, code BIGINT NOT NULL DEFAULT 7"),
            ("b", "id int32 generated by default as identity, code int64 default 7", "id INTEGER GENERATED BY DEFAULT AS IDENTITY, code BIGINT NOT NULL DEFAULT 7"),
            ("c", "id bigserial, code int64 default 7", "id BIGSERIAL, code BIGINT NOT NULL DEFAULT 7"),
            ("n", "id int64 default nextval(t_id_seq), code nullable int64 default null, price nullable numeric default -1.5", "id BIGINT NOT NULL DEFAULT nextval('t_id_seq'), code BIGINT DEFAULT NULL, price NUMERIC DEFAULT -1.5"),
        ];
        for (table, native, ddl) in cases {
            let text = format!("create table {table} ({native}, primary key (id))");
            let ast = trap(|| parse_catalog_with_version(&text, V)).unwrap();
            let bound = trap(|| engine.prepare_catalog_bound(&ast)).unwrap();
            if table == "c" { trap(|| engine.execute_catalog_optional(&ast)).unwrap_or_else(|e| panic!("{storage:?}/{table}: {e:?}")).unwrap(); }
            else if table == "b" { trap(|| engine.execute_catalog_text(&text)).unwrap_or_else(|e| panic!("{storage:?}/{table}: {e:?}")); }
            else { trap(|| engine.execute_catalog_bound(&bound)).unwrap_or_else(|e| panic!("{storage:?}/{table}: {e:?}")); }
            sql.execute(&format!("CREATE TABLE {table} ({ddl}, PRIMARY KEY(id))"), &[], None).unwrap();
            assert_eq!(snapshot(&left), snapshot(&right));
            let columns = format!("SELECT column_name, column_default FROM information_schema.columns WHERE table_name = '{table}' ORDER BY ordinal_position");
            match sql.execute(&columns, &[], None) {
                Ok(expected) => assert_eq!(values(right.sql_session().execute(&columns, &[], None).unwrap().rows), values(expected.rows)),
                Err(error) => {
                    assert_eq!(giggles_core::sqlstate(&error), "42P01");
                    assert_eq!(giggles_core::sqlstate(&right.sql_session().execute(&columns, &[], None).unwrap_err()), "42P01");
                    let describe = format!("describe table {table}");
                    let InspectionOutcome::Catalog(actual) = trap(|| engine.inspect_text(&describe)).unwrap() else { panic!(); };
                    let InspectionOutcome::Catalog(expected) = trap(|| Engine::with_version(left.clone(), V).inspect_text(&describe)).unwrap() else { panic!(); };
                    assert_eq!(actual.result, expected.result);
                }
            }
        }
        for (table, _, _) in cases {
            for _ in 0..2 {
                let n = trap(|| engine.execute_text(&format!("insert into {table}(code) values(1)"), &Bindings::new())).unwrap();
                let s = sql.execute_at(&format!("INSERT INTO {table}(code) VALUES(1)"), &[], None, &clock).unwrap_or_else(|e| panic!("{storage:?}/{table}: {e:?}"));
                assert_eq!(n.affected as u64, s.affected);
            }
            if table != "n" {
                let ids = right.sql_session().execute(&format!("SELECT id FROM {table} ORDER BY id"), &[], None).unwrap().rows;
                assert_eq!(ids.iter().map(|r| r.values[0].clone()).collect::<Vec<_>>(), vec![Value::Int(1), Value::Int(2)]);
            }
            let query = format!("SELECT * FROM {table} ORDER BY id");
            assert_eq!(values(left.sql_session().execute(&query, &[], None).unwrap().rows), values(right.sql_session().execute(&query, &[], None).unwrap().rows));
        }
        let err = trap(|| engine.execute_text("insert into a(id) values(9)", &Bindings::new())).unwrap_err();
        assert_eq!(err, Error::Sql { sqlstate: "428C9".into() });
        assert_eq!(giggles_core::sqlstate(&sql.execute_at("INSERT INTO a(id) VALUES(9)", &[], None, &clock).unwrap_err()), "428C9");
        trap(|| engine.execute_text("insert into b(id) values(9)", &Bindings::new())).unwrap();
        sql.execute_at("INSERT INTO b(id) VALUES(9)", &[], None, &clock).unwrap();
        assert_eq!(values(left.sql_session().execute("SELECT * FROM b ORDER BY id", &[], None).unwrap().rows), values(right.sql_session().execute("SELECT * FROM b ORDER BY id", &[], None).unwrap().rows));
        assert_eq!(snapshot(&left), snapshot(&right));
        let defaults = right.catalog_presentation().unwrap().defaults;
        assert!(defaults.values().any(|v| v == "'x'::text"));
        assert!(defaults.values().any(|v| v == "1.5"));
    }
}
#[test]
fn default_errors_match_sql() {
    for storage in storages() {
        let (_l, left) = Db::fresh(storage); let (_r, right) = Db::fresh(storage);
        let engine = Engine::with_version(right.clone(), V);
        for (native, sql, state) in [
            ("id text generated always as identity", "id TEXT GENERATED ALWAYS AS IDENTITY", "22023"),
            ("id int64 default 1 generated always as identity", "id BIGINT GENERATED ALWAYS AS IDENTITY DEFAULT 1", "42601"),
            ("id int64 default 'abc'", "id BIGINT DEFAULT 'abc'::text", "42804"),
        ] {
            let err = trap(|| engine.execute_catalog_text(&format!("create table t ({native}, primary key(id))"))).unwrap_err();
            assert_eq!(err, Error::Sql { sqlstate: state.into() });
            assert_eq!(giggles_core::sqlstate(&left.sql_session().execute(&format!("CREATE TABLE t ({sql}, PRIMARY KEY(id))"), &[], None).unwrap_err()), state);
        }
        // Repo SQL's DEFAULT-before-GENERATED spelling is narrower than PG18.6/native.
        assert_eq!(giggles_core::sqlstate(&left.sql_session().execute("CREATE TABLE syntax_order(id BIGINT DEFAULT 1 GENERATED ALWAYS AS IDENTITY PRIMARY KEY)", &[], None).unwrap_err()), "0A000");
        // Native typed text defaults do not acquire SQL's unknown-literal coercion.
        assert_eq!(trap(|| engine.execute_catalog_text("create table t(id int64 default '5', primary key(id))")), Err(Error::Sql { sqlstate: "42804".into() }));
        left.sql_session().execute("CREATE TABLE t(id BIGINT DEFAULT '5' PRIMARY KEY)", &[], None).unwrap();
        assert!(matches!(trap(|| engine.execute_catalog_text("create table t(id nullable serial, primary key(id))")), Err(Error::Syntax { .. })));
        // PG18.6 rejects SERIAL NULL (42601); repo SQL accepts and retains NOT NULL.
        assert_eq!(left.sql_session().execute("CREATE TABLE bad(id SERIAL NULL PRIMARY KEY)", &[], None).unwrap().affected, 0);
        assert!(left.catalog().unwrap().1.iter().find(|t| t.name == "bad").unwrap().columns[0].not_null);
        assert_eq!(trap(|| engine.execute_catalog_text("create table t(id int64 default $p, primary key(id))")), Err(Error::Unsupported));
        assert!(matches!(trap(|| engine.execute_catalog_text("create table t(id int64 default now(), primary key(id))")), Err(Error::Syntax { .. })));
        for text in ["create table p(id serial generated always as identity, primary key(id))", "create table p(id text default 'unterminated, primary key(id))"] {
            assert!(matches!(parse_catalog_with_version(text, V), Err(Error::Syntax { .. })));
        }
        let escaped = parse_catalog_with_version("create table p(id text default 'it''s', primary key(id))", V).unwrap();
        if let CatalogStatement::CreateTableWith { columns, .. } = escaped { assert_eq!(columns[0].default, Some(ColumnDefaultSpec::Value(Value::Text("it's".into())))); } else { panic!(); }
        assert!(matches!(parse_catalog_with_version("create table p(id text default 'x', primary key(id))", LanguageVersion::Embedded020), Err(Error::Syntax { .. })));
        assert!(parse_catalog_with_version("create table p(id text default \"x\", primary key(id))", V).is_ok());
        let plain = parse_catalog_with_version("create table p(id int64, primary key(id))", V).unwrap();
        assert!(matches!(plain, CatalogStatement::CreateTable { .. }));
        assert_eq!(parse_catalog_with_version("create table p(id serial, primary key(id))", LanguageVersion::Embedded020), Err(Error::Unsupported));
        let mut ast = parse_catalog_with_version("create table p(id serial, primary key(id))", V).unwrap();
        assert_eq!(trap(|| Engine::with_version(right.clone(), LanguageVersion::Embedded020).execute_catalog(&ast)), Err(Error::Unsupported));
        if let CatalogStatement::CreateTableWith { constraints, .. } = &mut ast { constraints.push(TableConstraint { name: None, constraint: ConstraintSpec::Unique { columns: vec!["id".into()] } }); }
        assert_eq!(trap(|| engine.execute_catalog_optional(&ast)), Err(Error::Unsupported));
    }
}
