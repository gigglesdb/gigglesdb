//! Structural coverage for row-source injection, independent of row-map storage.
use super::scan::{Direction, KeyRange, LegacyRows, RowSource, SourceRow};
use super::*;
use std::cell::Cell;

struct CountingSource<'a> {
    legacy: LegacyRows<'a>,
    scans: Cell<usize>,
    gets: Cell<usize>,
    contains: Cell<usize>,
}

impl<'a> CountingSource<'a> {
    fn new(state: &'a Relational) -> Self {
        Self {
            legacy: LegacyRows(state),
            scans: Cell::new(0),
            gets: Cell::new(0),
            contains: Cell::new(0),
        }
    }

    fn assert_calls(&self, scans: usize, gets: usize, contains: usize) {
        assert!(
            self.scans.get() >= scans,
            "scan calls: {}",
            self.scans.get()
        );
        assert!(self.gets.get() >= gets, "get calls: {}", self.gets.get());
        assert!(
            self.contains.get() >= contains,
            "contains calls: {}",
            self.contains.get()
        );
    }
}

impl RowSource for CountingSource<'_> {
    fn scan<'s>(
        &'s self,
        table: &TableDef,
        range: &KeyRange,
        dir: Direction,
    ) -> R<Box<dyn Iterator<Item = R<SourceRow<'s>>> + 's>> {
        self.scans.set(self.scans.get() + 1);
        self.legacy.scan(table, range, dir)
    }

    fn get<'s>(&'s self, table: &TableDef, key: &[u8]) -> R<Option<SourceRow<'s>>> {
        self.gets.set(self.gets.get() + 1);
        self.legacy.get(table, key)
    }

    fn contains(&self, table: &TableDef, key: &[u8]) -> R<bool> {
        self.contains.set(self.contains.get() + 1);
        self.legacy.contains(table, key)
    }
}

fn run(state: &mut Relational, sql: &str) -> SqlResult {
    let prepared = Prepared::parse(sql, 1, state.epoch).unwrap();
    state.execute(&prepared, &[], None).unwrap()
}

fn fixture() -> Relational {
    let mut state = Relational::default();
    for sql in [
        "CREATE TABLE source_t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, bucket BIGINT, n BIGINT)",
        "CREATE TABLE source_u (id BIGINT PRIMARY KEY, label TEXT)",
        "INSERT INTO source_t VALUES (1, 10, 5)",
        "INSERT INTO source_t VALUES (2, 10, 7)",
        "INSERT INTO source_t VALUES (3, 20, 9)",
        "INSERT INTO source_u VALUES (10, 'ten')",
        "INSERT INTO source_u VALUES (20, 'twenty')",
    ] {
        run(&mut state, sql);
    }
    state
}

fn query_from_source<'a>(
    snapshot: &'a Relational,
    prepared: &Prepared,
    params: &[Value],
) -> (SqlResult, CountingSource<'a>) {
    let mut production = snapshot.clone();
    let expected = production.execute(prepared, params, None).unwrap();
    // Binding still has the full catalog, but every row must come from source.
    let mut catalog_only = snapshot.clone();
    catalog_only.rows.clear();
    let before = catalog_only.clone();
    let plain = catalog_only
        .execute_with_source(prepared, params, None, &LegacyRows(snapshot))
        .unwrap();
    assert_eq!(plain, expected);
    let counted = CountingSource::new(snapshot);
    let actual = catalog_only
        .execute_with_source(prepared, params, None, &counted)
        .unwrap();
    assert_eq!(actual, expected);
    assert_eq!(catalog_only, before);
    (actual, counted)
}

#[test]
fn filtered_query_reads_only_the_supplied_source() {
    let state = fixture();
    let prepared = Prepared::parse(
        "SELECT id, n FROM source_t WHERE n > $1 ORDER BY id",
        1,
        state.epoch,
    )
    .unwrap();
    let (result, source) = query_from_source(&state, &prepared, &[Value::Int(5)]);
    source.assert_calls(1, 0, 0);
    assert_eq!(
        result
            .rows
            .iter()
            .map(|r| r.values.clone())
            .collect::<Vec<_>>(),
        vec![
            vec![Value::Int(2), Value::Int(7)],
            vec![Value::Int(3), Value::Int(9)]
        ]
    );
}

#[test]
fn legacy_point_select_reads_only_the_supplied_source() {
    let state = fixture();
    // SQL SELECT parsing uses Query; construct the native legacy arm explicitly.
    let prepared = Prepared::engine(
        Statement::Select {
            name: "source_t".into(),
            projection: vec!["id".into(), "n".into()],
            predicates: vec![Predicate {
                column: "id".into(),
                op: "=".into(),
                value: Expr::Literal(Value::Int(2)),
            }],
            order: vec![],
            limit: None,
        },
        1,
        state.epoch,
    );
    let (result, source) = query_from_source(&state, &prepared, &[]);
    source.assert_calls(0, 1, 0);
    assert_eq!(result.rows.len(), 1);
    assert_eq!(result.rows[0].values, vec![Value::Int(2), Value::Int(7)]);

    let mut zero_limit = prepared;
    if let Statement::Select { limit, .. } = zero_limit.statement.get_mut() {
        *limit = Some(Expr::Literal(Value::Int(0)));
    }
    let (result, _) = query_from_source(&state, &zero_limit, &[]);
    assert!(result.rows.is_empty());
}

#[test]
fn legacy_range_select_preserves_reverse_limit_and_empty_bounds() {
    let state = fixture();
    let mut prepared = Prepared::engine(
        Statement::Select {
            name: "source_t".into(),
            projection: vec!["id".into()],
            predicates: vec![
                Predicate {
                    column: "id".into(),
                    op: ">=".into(),
                    value: Expr::Literal(Value::Int(1)),
                },
                Predicate {
                    column: "id".into(),
                    op: "<=".into(),
                    value: Expr::Literal(Value::Int(3)),
                },
            ],
            order: vec![("id".into(), true)],
            limit: Some(Expr::Literal(Value::Int(2))),
        },
        1,
        state.epoch,
    );
    let (result, source) = query_from_source(&state, &prepared, &[]);
    source.assert_calls(1, 0, 0);
    assert_eq!(
        result
            .rows
            .into_iter()
            .map(|r| r.values)
            .collect::<Vec<_>>(),
        vec![vec![Value::Int(3)], vec![Value::Int(2)]]
    );

    if let Statement::Select { predicates, .. } = prepared.statement.get_mut() {
        predicates[0].value = Expr::Literal(Value::Int(4));
    }
    let (result, _) = query_from_source(&state, &prepared, &[]);
    assert!(result.rows.is_empty());
}

#[test]
fn join_lookups_read_only_the_supplied_source() {
    let state = fixture();
    let prepared = Prepared::parse(
        "SELECT t.id, u.label FROM source_t t JOIN source_u u ON u.id = t.bucket ORDER BY t.id",
        1,
        state.epoch,
    )
    .unwrap();
    let (result, source) = query_from_source(&state, &prepared, &[]);
    // one get per distinct join key per statement (join PK-lookup cache)
    source.assert_calls(1, 2, 0);
    assert_eq!(result.rows.len(), 3);
    assert_eq!(
        result.rows[2].values,
        vec![Value::Int(3), Value::Text("twenty".into())]
    );
}

#[test]
fn grouped_and_aggregate_queries_read_only_the_supplied_source() {
    let state = fixture();
    for (sql, gets, expected_rows) in [
        (
            "SELECT bucket, count(*) FROM source_t GROUP BY bucket ORDER BY bucket",
            0,
            vec![
                vec![Value::Int(10), Value::Int(2)],
                vec![Value::Int(20), Value::Int(1)],
            ],
        ),
        (
            "SELECT u.label, count(*) FROM source_t t JOIN source_u u ON u.id = t.bucket GROUP BY u.label ORDER BY u.label",
            // one get per distinct join key per statement (join PK-lookup cache)
            2,
            vec![
                vec![Value::Text("ten".into()), Value::Int(2)],
                vec![Value::Text("twenty".into()), Value::Int(1)],
            ],
        ),
        (
            "SELECT count(*) FROM source_t",
            0,
            vec![vec![Value::Int(3)]],
        ),
    ] {
        let prepared = Prepared::parse(sql, 1, state.epoch).unwrap();
        let (result, source) = query_from_source(&state, &prepared, &[]);
        source.assert_calls(1, gets, 0);
        assert_eq!(
            result
                .rows
                .into_iter()
                .map(|r| r.values)
                .collect::<Vec<_>>(),
            expected_rows
        );
    }
}

fn mutation_from_source<'a>(
    snapshot: &'a Relational,
    sql: &str,
) -> (R<SqlResult>, Relational, CountingSource<'a>) {
    let prepared = Prepared::parse(sql, 1, snapshot.epoch).unwrap();
    let mut production = snapshot.clone();
    let expected = production.execute(&prepared, &[], None);
    // The publisher retains actual preimages; readers use a separate snapshot.
    let mut plain = snapshot.clone();
    assert_eq!(
        plain.execute_with_source(&prepared, &[], None, &LegacyRows(snapshot)),
        expected
    );
    assert_eq!(plain, production);
    let mut actual = snapshot.clone();
    let source = CountingSource::new(snapshot);
    let result = actual.execute_with_source(&prepared, &[], None, &source);
    assert_eq!(result, expected);
    assert_eq!(actual, production);
    actual.validate().unwrap();
    (result, actual, source)
}

#[test]
fn point_mutations_read_the_supplied_source() {
    let state = fixture();
    for sql in [
        "UPDATE source_t SET n = 40 WHERE id = 2 RETURNING id, n",
        "DELETE FROM source_t WHERE id = 2 RETURNING id, n",
    ] {
        let (result, _, source) = mutation_from_source(&state, sql);
        source.assert_calls(0, 1, 0);
        let result = result.unwrap();
        assert_eq!(result.affected, 1);
        assert_eq!(result.rows.len(), 1);
    }
}

#[test]
fn searched_mutations_read_and_check_existence_through_the_supplied_source() {
    let state = fixture();
    let (result, updated, source) = mutation_from_source(
        &state,
        "UPDATE source_t SET id = id + 10 WHERE bucket = 10 RETURNING id, n",
    );
    // Each of the two moved keys needs uniqueness, capacity and publication checks.
    source.assert_calls(1, 0, 6);
    assert_eq!(result.unwrap().affected, 2);
    let table = &state.tables["source_t"];
    assert!(updated.rows[&table.id].contains_key(&encode_key(&[Value::Int(11)]).unwrap()));
    assert!(updated.rows[&table.id].contains_key(&encode_key(&[Value::Int(12)]).unwrap()));

    let (result, deleted, source) = mutation_from_source(
        &state,
        "DELETE FROM source_t WHERE bucket = 10 RETURNING id, n",
    );
    source.assert_calls(1, 0, 0);
    assert_eq!(result.unwrap().affected, 2);
    assert_eq!(deleted.rows[&table.id].len(), 1);
}

#[test]
fn searched_duplicate_failure_preserves_precedence_and_state() {
    let state = fixture();
    let (result, after, source) =
        mutation_from_source(&state, "UPDATE source_t SET id = id + 1 WHERE bucket = 10");
    source.assert_calls(1, 0, 1);
    assert_eq!(result, Err(SqlError::Duplicate));
    assert_eq!(after, state);
}

#[test]
fn default_contains_uses_get_through_a_trait_object() {
    struct DefaultContains<'a>(CountingSource<'a>);
    impl RowSource for DefaultContains<'_> {
        fn scan<'s>(
            &'s self,
            table: &TableDef,
            range: &KeyRange,
            dir: Direction,
        ) -> R<Box<dyn Iterator<Item = R<SourceRow<'s>>> + 's>> {
            self.0.scan(table, range, dir)
        }

        fn get<'s>(&'s self, table: &TableDef, key: &[u8]) -> R<Option<SourceRow<'s>>> {
            self.0.get(table, key)
        }
    }
    let state = fixture();
    let table = &state.tables["source_t"];
    let source = DefaultContains(CountingSource::new(&state));
    let object: &dyn RowSource = &source;
    assert!(
        object
            .contains(table, &encode_key(&[Value::Int(1)]).unwrap())
            .unwrap()
    );
    assert!(
        !object
            .contains(table, &encode_key(&[Value::Int(99)]).unwrap())
            .unwrap()
    );
    assert_eq!(source.0.gets.get(), 2);
    assert_eq!(source.0.contains.get(), 0);
}

#[test]
fn mutation_source_read_errors_are_propagated_without_publication() {
    struct Unreadable;
    impl RowSource for Unreadable {
        fn scan<'s>(
            &'s self,
            _table: &TableDef,
            _range: &KeyRange,
            _dir: Direction,
        ) -> R<Box<dyn Iterator<Item = R<SourceRow<'s>>> + 's>> {
            Err(SqlError::Aborted)
        }

        fn get<'s>(&'s self, _table: &TableDef, _key: &[u8]) -> R<Option<SourceRow<'s>>> {
            Err(SqlError::Aborted)
        }
    }
    let snapshot = fixture();
    let source: &dyn RowSource = &Unreadable;
    assert_eq!(
        source.contains(&snapshot.tables["source_t"], &[]),
        Err(SqlError::Aborted)
    );
    for sql in [
        "UPDATE source_t SET n = 40 WHERE id = 2",
        "DELETE FROM source_t WHERE id = 2",
        "UPDATE source_t SET n = 40 WHERE bucket = 10",
        "DELETE FROM source_t WHERE bucket = 10",
    ] {
        let prepared = Prepared::parse(sql, 1, snapshot.epoch).unwrap();
        let mut state = snapshot.clone();
        assert_eq!(
            state.execute_with_source(&prepared, &[], None, source),
            Err(SqlError::Aborted)
        );
        assert_eq!(state, snapshot);
    }
}
