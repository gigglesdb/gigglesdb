mod common;
use giggles_core::{Admin, Limits, Engine as Backend};
use giggles_core::operations::{Bindings, CatalogRequest, ColumnSpec, ColumnDefault as D, ClockDefault as C, Generated as G, Engine, Error, Request};
use giggles_core::relational::{DataType as T, Value as V};

fn column(name: &str, ty: T, default: Option<D>, generated: Option<G>) -> ColumnSpec {
    ColumnSpec { name: name.into(), data_type: ty, not_null: false, default, generated }
}
fn create(table: &str, columns: Vec<ColumnSpec>) -> CatalogRequest {
    CatalogRequest::CreateTable { table: table.into(), columns, primary_key: vec!["id".into()] }
}
// These are the metadata fields consumed by information_schema.columns in the wire adapter.
fn sequences(admin: &Admin, prefix: &str) -> Vec<(String, Option<String>)> {
    admin.sql_session().sequence_owners().unwrap().into_iter().filter(|(name, _)| name.starts_with(&format!("{prefix}_"))).map(|(name, owner)|
        (name.replacen(&format!("{prefix}_"), "x_", 1), owner.map(|o| o.replacen(&format!("{prefix}_"), "x_", 1)))
    ).collect()
}
fn catalog(admin: &Admin, table: &str) -> Vec<Vec<V>> {
    let presentation = admin.catalog_presentation().unwrap();
    let definition = admin.catalog().unwrap().1.into_iter().find(|t| t.name == table).unwrap();
    definition.columns.iter().map(|c| {
        let identity = presentation.identities.get(&c.id);
        vec![presentation.defaults.get(&c.id).map_or(V::Null, |s| V::Text(s.replace(&format!("{table}_"), "x_"))),
            V::Bool(!c.not_null), V::Bool(identity.is_some()),
            identity.map_or(V::Null, |i| V::Text(if *i == 'a' { "ALWAYS" } else { "BY DEFAULT" }.into()))]
    }).collect()
}
#[test]
fn typed_defaults_generated_and_reopen_match_sql() {
    for backend in [Backend::Legacy, Backend::V2] {
        if backend == Backend::V2 && !cfg!(feature = "engine-rocksdb") { continue; }
        let path = common::fresh("native-create-defaults");
        let admin = if backend == Backend::Legacy { Admin::create(&path, Limits::default()).unwrap() }
            else { Admin::create_engine(&path, Limits::default(), backend).unwrap() };
        let engine = Engine::new(admin.clone());
        let mut sql = admin.sql_session();
        let clock = giggles_core::relational::StatementClock { unavailable: None, transaction_us: 1_000_000, statement_us: 1_000_000, zone: None, wall: None };
        for (suffix, generated, ty, definition) in [("always", G::IdentityAlways, T::SmallInt, "SMALLINT GENERATED ALWAYS AS IDENTITY"), ("bydefault", G::IdentityByDefault, T::Integer, "INTEGER GENERATED BY DEFAULT AS IDENTITY"), ("serial", G::Serial, T::BigInt, "BIGSERIAL"), ("serialsmall", G::Serial, T::SmallInt, "SMALLSERIAL"), ("serialint", G::Serial, T::Integer, "SERIAL")] {
            let n = format!("n_{suffix}"); let s = format!("s_{suffix}");
            let columns = vec![column("id", ty, None, Some(generated)),
                column("i", T::Integer, Some(D::Value(V::Int(7))), None),
                column("n", T::Numeric, Some(D::Value(V::Numeric(giggles_pg_types::Numeric::parse("1.5").unwrap()))), None),
                column("t", T::Text, Some(D::Value(V::Text("x".into()))), None),
                column("d", T::Date, Some(D::Value(V::Date(giggles_core::relational::Date::parse("2024-01-02", &Default::default()).unwrap()))), None),
                column("b", T::Boolean, Some(D::Value(V::Bool(true))), None),
                column("neg", T::BigInt, Some(D::Value(V::Int(-3))), None),
                column("nan", T::Numeric, Some(D::Value(V::Numeric(giggles_pg_types::Numeric::parse("NaN").unwrap()))), None),
                column("f", T::DoublePrecision, Some(D::Value(V::Float8(giggles_pg_types::Float8::parse("2.5").unwrap()))), None),
                column("supplied", T::Integer, None, None)];
            engine.execute_catalog(&create(&n, columns)).unwrap();
            sql.execute(&format!("CREATE TABLE {s} (id {definition} PRIMARY KEY, i INTEGER DEFAULT 7, n NUMERIC DEFAULT 1.5, t TEXT DEFAULT 'x'::text, d DATE DEFAULT '2024-01-02'::date, b BOOLEAN DEFAULT true, neg BIGINT DEFAULT -3, nan NUMERIC DEFAULT 'NaN'::numeric, f DOUBLE PRECISION DEFAULT '2.5'::double precision, supplied INTEGER)"), &[], None).unwrap();
            let nc = catalog(&admin, &n);
            assert_eq!(nc, catalog(&admin, &s));
            for (i, expected) in [(1, "7"), (2, "1.5"), (3, "'x'::text"), (4, "'2024-01-02'::date"), (5, "true"), (6, "'-3'::integer"), (7, "'NaN'::numeric"), (8, "'2.5'::double precision")] {
                assert_eq!(nc[i][0], V::Text(expected.into()));
            }
        }
        let mut id = column("id", T::BigInt, None, None); id.not_null = true;
        engine.execute_catalog(&create("n_clock", vec![id, column("clock", T::TimestampTz, Some(D::Clock(C::Now)), None)])).unwrap();
        sql.execute("CREATE TABLE s_clock (id BIGINT PRIMARY KEY, clock TIMESTAMPTZ DEFAULT now())", &[], None).unwrap();
        assert_eq!(catalog(&admin, "n_clock"), catalog(&admin, "s_clock"));
        assert_eq!(catalog(&admin, "n_clock")[1][0], V::Text("now()".into()));
        for (suffix, generated) in [("always", G::IdentityAlways), ("bydefault", G::IdentityByDefault), ("serial", G::Serial), ("serialsmall", G::Serial), ("serialint", G::Serial)] {
            let n = format!("n_{suffix}"); let s = format!("s_{suffix}");
            let native_insert = engine.execute(&Request::Insert { table: n.clone(), values: vec![("supplied".into(), giggles_core::operations::ValueExpr::Literal(V::Int(1)))] }, &Bindings::new()).unwrap();
            let sql_insert = sql.execute_at(&format!("INSERT INTO {s} (supplied) VALUES (1)"), &[], None, &clock).unwrap();
            assert_eq!(native_insert.affected, 1);
            assert_eq!(native_insert.affected as u64, sql_insert.affected);
            let nr = sql.execute(&format!("SELECT * FROM {n} LIMIT 10"), &[], None).unwrap();
            let sr = sql.execute(&format!("SELECT * FROM {s} LIMIT 10"), &[], None).unwrap();
            assert_eq!(nr.rows[0].values[0], V::Int(1));
            assert_eq!(nr.rows[0].values, sr.rows[0].values);
            if generated == G::IdentityAlways {
                let request = Request::Insert { table: n, values: vec![("id".into(), giggles_core::operations::ValueExpr::Literal(V::Int(9)))] };
                assert_eq!(engine.execute(&request, &Bindings::new()).unwrap_err(), Error::Sql { sqlstate: "428C9".into() });
                assert_eq!(giggles_core::sqlstate(&sql.execute_at(&format!("INSERT INTO {s} (id) VALUES (9)"), &[], None, &clock).unwrap_err()), "428C9");
            }
        }
        // Native Engine has no time input: omitted clocks retain the existing explicit error.
        let insert = Request::Insert { table: "n_clock".into(), values: vec![("id".into(), giggles_core::operations::ValueExpr::Literal(V::Int(1)))] };
        assert_eq!(engine.execute(&insert, &Bindings::new()).unwrap_err(), Error::Sql { sqlstate: "0A000".into() });
        assert_eq!(giggles_core::sqlstate(&sql.execute("INSERT INTO s_clock (id) VALUES (1)", &[], None).unwrap_err()), "0A000");
        for table in ["n_clock", "s_clock"] {
            sql.execute_at(&format!("INSERT INTO {table} (id) VALUES (2)"), &[], None, &clock).unwrap();
            let row = sql.execute(&format!("SELECT clock FROM {table} LIMIT 10"), &[], None).unwrap();
            assert!(matches!(row.rows[0].values[0], V::TimestampTz(_)));
        }
        let seq = sequences(&admin, "n");
        assert_eq!(seq.len(), 5);
        assert_eq!(seq, sequences(&admin, "s"));
        let expected: Vec<_> = ["always", "bydefault", "serial", "serialsmall", "serialint"].into_iter().map(|s| catalog(&admin, &format!("n_{s}"))).collect();
        drop(sql); drop(engine); drop(admin);
        let reopened = Admin::open(&path, Limits::default()).unwrap();
        assert_eq!(sequences(&reopened, "n"), seq);
        assert_eq!(sequences(&reopened, "s"), seq);
        assert_eq!(catalog(&reopened, "n_clock"), catalog(&reopened, "s_clock"));
        assert_eq!(catalog(&reopened, "n_clock")[1][0], V::Text("now()".into()));
        for (index, suffix) in ["always", "bydefault", "serial", "serialsmall", "serialint"].into_iter().enumerate() {
            assert_eq!(catalog(&reopened, &format!("n_{suffix}")), expected[index]);
            assert_eq!(catalog(&reopened, &format!("s_{suffix}")), expected[index]);
        }
    }
}
#[test]
fn native_default_errors_and_legacy_json() {
    for backend in [Backend::Legacy, Backend::V2] {
    if backend == Backend::V2 && !cfg!(feature = "engine-rocksdb") { continue; }
    let admin = Admin::create_engine(common::fresh("native-default-errors"), Limits::default(), backend).unwrap();
    let engine = Engine::new(admin);
    for (default, generated, ty, state) in [
        (Some(D::Value(V::Text("abc".into()))), None, T::Integer, "42804"),
        (None, Some(G::IdentityAlways), T::Text, "22023"),
        (None, Some(G::Serial), T::Text, "22023"),
        (Some(D::Value(V::Int(1))), Some(G::IdentityAlways), T::BigInt, "42601"),
        (Some(D::Value(V::Int(1))), Some(G::Serial), T::BigInt, "42601"),
    ] {
        let mut id = column("id", T::BigInt, None, None); id.not_null = true;
        let request = create("invalid", vec![id, column("v", ty, default, generated)]);
        assert_eq!(engine.execute_catalog(&request).unwrap_err(), Error::Sql { sqlstate: state.into() });
    }
    }
    let json = r#"{"name":"id","data_type":"BigInt","not_null":true}"#;
    let old: ColumnSpec = serde_json::from_str(json).unwrap();
    assert!(old.default.is_none() && old.generated.is_none());
    assert_eq!(serde_json::to_string(&old).unwrap(), json);
}
