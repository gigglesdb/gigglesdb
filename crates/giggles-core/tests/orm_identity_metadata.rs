use giggles_core::{
    Admin, Limits,
    relational::{StatementClock, Value},
};
use giggles_pg_types::temporal::{SessionZone, TimestampTz};

#[test]
fn identity_and_serial_precede_character_metadata() {
    let path = std::env::temp_dir().join(format!("orm-identity-{}", std::process::id()));
    let admin = Admin::create(&path, Limits::default()).unwrap();
    let mut session = admin.sql_session();
    let clock = StatementClock {
        unavailable: None,
        transaction_us: 0,
        statement_us: 0,
        zone: Some(SessionZone::Fixed(0)),
        wall: None,
    };
    let stamp = Value::TimestampTz(TimestampTz::from_microseconds(0).unwrap());
    for (name, id) in [
        ("recorder", "integer GENERATED BY DEFAULT AS IDENTITY"),
        ("serials", "serial"),
    ] {
        session.execute_at(&format!("CREATE TABLE {name} (id {id} PRIMARY KEY, app varchar(255) NOT NULL, name char(8) NOT NULL, applied timestamp with time zone NOT NULL)"), &[], None, &clock).unwrap();
        let result = session.execute_at(&format!("INSERT INTO {name} (app, name, applied) VALUES ('shop', 'initial', $1) RETURNING id, app"), std::slice::from_ref(&stamp), None, &clock).unwrap();
        assert_eq!(
            result.rows[0].values,
            vec![Value::Int(1), Value::Text("shop".into())]
        );
    }
    drop(session);
    drop(admin);
    let admin = Admin::open(&path, Limits::default()).unwrap();
    let result = admin
        .sql_session()
        .execute_at(
            "INSERT INTO recorder (app, name, applied) VALUES ('shop', 'next', $1) RETURNING id",
            &[stamp],
            None,
            &clock,
        )
        .unwrap();
    assert!(matches!(result.rows[0].values[0], Value::Int(id) if id > 1));
    drop(admin);
    std::fs::remove_dir_all(path).unwrap();
}
