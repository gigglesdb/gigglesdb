mod api_support;
use api_support::{Fixture, rpc};
use giggles_server::api::{json as wire_json, proto as p};
use serde_json::{Value, json};
async fn execute(f: &Fixture, t: &str, v: Value, g: bool) -> Value {
    if g {
        let q = wire_json::decode_execute(&serde_json::to_vec(&v).unwrap()).unwrap();
        let r = f.grpc_client(&f.app).await.execute(rpc(t, q)).await.unwrap().into_inner();
        serde_json::from_slice(&wire_json::encode_reply(&r).unwrap()).unwrap()
    } else {
        let (s, b) = f.http(&f.app, "POST", "/v1/session/execute", Some(t), serde_json::to_vec(&v).unwrap(), false).await.unwrap();
        assert_eq!(s, 200, "{}", String::from_utf8_lossy(&b));
        serde_json::from_slice(&b).unwrap()
    }
}
fn code(v: &Value, s: &str) {
    assert_eq!(if v["code"] == "native_error" { &v["nativeError"]["sqlstate"] } else { &v["code"] }, s, "{v}");
}
fn bind(f: &Fixture, r: &str) {
    let mut b = f.bindings.clone();
    b[0].role = giggles_server::Role::Database { name: r.into() };
    f.service.reload_bindings(b).unwrap();
}
fn setup(f: &Fixture) {
    f.admin.sql_session().execute("CREATE SCHEMA app", &[], None).unwrap();
    for (n, s) in [("owner", true), ("creator", false), ("denied", false)] {
        f.admin.roles().create(giggles_core::roles::NewRole { name: n.into(), login: true, superuser: s, ..Default::default() }).unwrap();
    }
    use giggles_core::roles::SchemaPrivilege::{Create, Usage};
    f.admin.roles().grant_schema("app", "creator", &[Usage, Create]).unwrap();
    bind(f, "owner");
}
fn create(t: &str, e: Value) -> Value {
    let mut c = json!({"name":"id","dataType":"BigInt","notNull":true});
    c.as_object_mut().unwrap().extend(e.as_object().unwrap().clone());
    json!({"catalog":{"createTable":{"table":t,"columns":[c],"primaryKey":["id"]}}})
}
#[tokio::test]
async fn defaults_and_generated_match_sql_twins() {
    use giggles_core::relational::Value as V;
    for g in [false, true] {
        for (suffix, extra, definition) in [
            ("literal", json!({"default":{"Value":{"intValue":"7"}}}), "BIGINT DEFAULT 7"),
            ("nextval", json!({"default":{"Nextval":"app.s"}}), "BIGINT DEFAULT nextval('app.s')"),
            ("serial", json!({"generated":"Serial"}), "BIGSERIAL"),
            ("always", json!({"generated":"IdentityAlways"}), "BIGINT GENERATED ALWAYS AS IDENTITY"),
            ("bydefault", json!({"generated":"IdentityByDefault"}), "BIGINT GENERATED BY DEFAULT AS IDENTITY"),
        ] {
            let f = Fixture::catalog_empty().await;
            let twin = Fixture::catalog_empty().await;
            setup(&f);
            setup(&twin);
            let token = f.open_http(&f.app, false).await;
            let mut n = f.service.role_session("owner").unwrap();
            let mut s = twin.service.role_session("owner").unwrap();
            for q in [&mut n, &mut s] {
                q.execute_sql("CREATE SEQUENCE app.s", &[]).unwrap();
            }
            let table = format!("app.{suffix}");
            let r = execute(&f, &token, create(&table, extra), g).await;
            code(&r, "ok");
            assert!(r["catalogOutcome"]["columns"][0].get("default").is_none());
            assert!(r["catalogOutcome"]["columns"][0].get("generated").is_none());
            s.execute_sql(&format!("CREATE TABLE {table}(id {definition} PRIMARY KEY)"), &[]).unwrap();
            for q in [&mut n, &mut s] {
                assert_eq!(q.execute_sql(&format!("INSERT INTO {table} DEFAULT VALUES"), &[]).unwrap().affected, 1);
            }
            let query = format!("SELECT * FROM {table}");
            let a = n.execute_sql(&query, &[]).unwrap();
            let b = s.execute_sql(&query, &[]).unwrap();
            assert_eq!(a.rows, b.rows);
            assert_eq!(a.columns, b.columns);
            assert_eq!(a.rows[0].values, vec![V::Int(if suffix == "literal" { 7 } else { 1 })]);
            if suffix == "always" {
                for q in [&mut n, &mut s] {
                    assert_eq!(
                        giggles_server::sqlstate(&q.execute_sql(&format!("INSERT INTO {table}(id) VALUES(9)"), &[]).unwrap_err()),
                        "428C9"
                    );
                }
            }
            f.stop().await;
            twin.stop().await;
        }
        for (suffix, ty, kind, definition) in
            [("date", "Date", "CurrentDate", "DATE DEFAULT CURRENT_DATE"), ("now", "TimestampTz", "Now", "TIMESTAMPTZ DEFAULT now()")]
        {
            let f = Fixture::catalog_empty().await;
            let twin = Fixture::catalog_empty().await;
            setup(&f);
            setup(&twin);
            let token = f.open_http(&f.app, false).await;
            let mut n = f.service.role_session("owner").unwrap();
            let mut s = twin.service.role_session("owner").unwrap();
            for q in [&mut n, &mut s] {
                q.execute_sql("CREATE SEQUENCE app.s", &[]).unwrap();
            }
            let table = format!("app.{suffix}");
            let mut v = create(&table, json!({}));
            v["catalog"]["createTable"]["columns"]
                .as_array_mut()
                .unwrap()
                .push(json!({"name":"v","dataType":ty,"default":{"Clock":{"kind":kind}}}));
            code(&execute(&f, &token, v, g).await, "ok");
            s.execute_sql(&format!("CREATE TABLE {table}(id BIGINT PRIMARY KEY,v {definition})"), &[]).unwrap();
            for q in [&mut n, &mut s] {
                q.execute_sql(&format!("INSERT INTO {table}(id) VALUES(1)"), &[]).unwrap();
                let r = q.execute_sql(&format!("SELECT v FROM {table}"), &[]).unwrap();
                assert!(matches!((&r.rows[0].values[0], kind), (V::Date(_), "CurrentDate") | (V::TimestampTz(_), "Now")), "{r:?}");
            }
            f.stop().await;
            twin.stop().await;
        }
        let f = Fixture::catalog_empty().await;
        let twin = Fixture::catalog_empty().await;
        setup(&f);
        setup(&twin);
        bind(&f, "creator");
        let t = f.open_http(&f.app, false).await;
        code(&execute(&f, &t, create("app.owned", json!({"generated":"Serial"})), g).await, "ok");
        let mut n = f.service.role_session("creator").unwrap();
        let mut s = twin.service.role_session("creator").unwrap();
        s.execute_sql("CREATE TABLE app.owned(id BIGSERIAL PRIMARY KEY)", &[]).unwrap();
        for q in [&mut n, &mut s] {
            assert_eq!(q.execute_sql("INSERT INTO app.owned DEFAULT VALUES", &[]).unwrap().affected, 1);
        }
        assert_eq!(
            n.execute_sql("SELECT * FROM app.owned", &[]).unwrap().rows,
            s.execute_sql("SELECT * FROM app.owned", &[]).unwrap().rows
        );
        f.stop().await;
        twin.stop().await;
    }
}
#[tokio::test]
async fn authority_precedes_default_binding() {
    for g in [false, true] {
        let f = Fixture::catalog_empty().await;
        setup(&f);
        for db in [false, true] {
            if db {
                bind(&f, "denied");
            } else {
                f.service.reload_bindings(f.bindings.clone()).unwrap();
            }
            let t = f.open_http(&f.app, false).await;
            for e in [json!({"default":{"Nextval":"app.missing"}}), json!({"default":{"Value":{"textValue":"wrong type"}}})] {
                code(&execute(&f, &t, create("app.denied", e), g).await, "42501");
            }
        }
        f.stop().await;
    }
}
fn proto_create(c: p::NativeCatalogColumn, alter: bool) -> p::ExecuteRequest {
    use p::{execute_request::Request as R, native_alter_table::Action as A, native_catalog_request::Request as C};
    let r = if alter {
        C::AlterTable(p::NativeAlterTable { table: Some("app.t".into()), action: Some(A::AddColumn(c)) })
    } else {
        C::CreateTable(p::NativeCreateTable { table: Some("app.t".into()), columns: vec![c], primary_key: vec!["id".into()] })
    };
    p::ExecuteRequest { request: Some(R::Catalog(p::NativeCatalogRequest { request: Some(r) })), ..Default::default() }
}
#[tokio::test]
async fn malformed_defaults_and_add_column_rejected() {
    use p::native_column_default::Kind as K;
    let f = Fixture::catalog_empty().await;
    setup(&f);
    let t = f.open_http(&f.app, false).await;
    let clock =
        |k: &str, precision| p::NativeColumnDefault { kind: Some(K::Clock(p::NativeClockDefault { kind: Some(k.into()), precision })) };
    let cases = vec![
        (json!({"generated":"unknown"}), None, Some("unknown".into()), false),
        (json!({"default":{"Clock":{"kind":"unknown"}}}), Some(clock("unknown", None)), None, false),
        (json!({"default":{"Clock":{"kind":"Now","precision":3}}}), Some(clock("Now", Some(3))), None, false),
        (json!({"default":{}}), Some(p::NativeColumnDefault::default()), None, false),
        (json!({"default":{"Nextval":"app.s"}}), Some(p::NativeColumnDefault { kind: Some(K::Nextval("app.s".into())) }), None, true),
        (json!({"generated":"Serial"}), None, Some("Serial".into()), true),
    ];
    let before = f.admin.catalog().unwrap();
    for (e, default, generated, alter) in cases {
        let mut v = create("app.t", e);
        if alter {
            v = json!({"catalog":{"alterTable":{"table":"app.t","addColumn":v["catalog"]["createTable"]["columns"][0]}}});
        }
        let (status, b) = f.http(&f.app, "POST", "/v1/session/execute", Some(&t), serde_json::to_vec(&v).unwrap(), false).await.unwrap();
        assert_eq!(status, 400, "{v}: {}", String::from_utf8_lossy(&b));
        assert_eq!(serde_json::from_slice::<Value>(&b).unwrap()["error"]["code"], "INVALID_ARGUMENT");
        let c =
            p::NativeCatalogColumn { name: Some("id".into()), data_type: Some("BigInt".into()), default, generated, ..Default::default() };
        let err = f.grpc_client(&f.app).await.execute(rpc(&t, proto_create(c, alter))).await.unwrap_err();
        assert_eq!(err.code(), tonic::Code::InvalidArgument, "{v}: {err}");
        assert_eq!(f.admin.catalog().unwrap(), before);
    }
    // Multiple oneof kinds and object keys cannot exist in typed protobuf.
    // Unknown protobuf fields are valid forward-compatible input, not errors.
    for e in [
        json!({"default":{"Value":{"intValue":"1"},"Nextval":"s"}}),
        json!({"default":{"Clock":{"kind":"Now","unknown":true}}}),
        json!({"unknown":true}),
    ] {
        let v = create("app.t", e);
        let (status, b) = f.http(&f.app, "POST", "/v1/session/execute", Some(&t), serde_json::to_vec(&v).unwrap(), false).await.unwrap();
        assert_eq!(status, 400, "{v}");
        assert_eq!(serde_json::from_slice::<Value>(&b).unwrap()["error"]["code"], "INVALID_ARGUMENT");
    }
    f.stop().await;
}
