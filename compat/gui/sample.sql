CREATE SCHEMA gui_sales;
CREATE SCHEMA gui_aux;
CREATE TABLE gui_sales.parent (id integer PRIMARY KEY, code text UNIQUE NOT NULL);
CREATE TABLE gui_sales.child (id integer PRIMARY KEY, parent_id integer REFERENCES gui_sales.parent(id), amount integer DEFAULT 7 CHECK (amount >= 0), label text UNIQUE);
CREATE INDEX child_amount_idx ON gui_sales.child(amount);
CREATE TABLE gui_aux.audit (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, note text DEFAULT 'sample');
CREATE VIEW gui_sales.child_view AS SELECT id, amount FROM gui_sales.child;
COMMENT ON TABLE gui_sales.child IS 'GUI qualification table';
COMMENT ON COLUMN gui_sales.child.amount IS 'Nonnegative amount';
