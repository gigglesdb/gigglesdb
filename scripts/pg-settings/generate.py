#!/usr/bin/env python3
"""Regenerate the server settings registry from the PostgreSQL 18.6 oracle."""
import argparse
import json
from pathlib import Path

SOURCE = Path(__file__).resolve().parent
DESTINATION = SOURCE.parents[1] / "crates/giggles-server/src/pg_settings_registry.rs"
EMPTY_PATHS = {"config_file", "data_directory", "hba_file", "ident_file", "external_pid_file"}
LOCALES = {"lc_messages", "lc_monetary", "lc_numeric", "lc_time"}


def literal(value):
    # The capture uses plain text and ordinary JSON string escapes.
    return json.dumps(value, ensure_ascii=False)


def optional(value):
    return "None" if value is None else f"Some({literal(value)})"


def render():
    rows = json.loads((SOURCE / "pg_settings-18.6.json").read_text(encoding="utf-8"))
    restricted = set((SOURCE / "superuser-only.txt").read_text(encoding="utf-8").split())
    assert len(rows) == 399 and len(restricted) == 24
    rows.sort(key=lambda row: row["name"].lower())
    names = [row["name"].lower() for row in rows]
    assert names == sorted(set(names)) and restricted <= {row["name"] for row in rows}
    lines = [
        "// Generated by scripts/pg-settings/generate.py from the PostgreSQL 18.6",
        "// pg_settings snapshot and non-superuser visibility capture in that directory.",
        "use super::{Context, Entry, Kind};",
        "",
        "#[rustfmt::skip]",
        "pub(crate) static ENTRIES: &[Entry] = &[",
    ]
    for row in rows:
        name = row["name"]
        default = row["reset_val"] or ""
        if name in EMPTY_PATHS:
            default = ""
        elif name in LOCALES:
            default = "C"
        elif name == "listen_addresses":
            default = row["boot_val"]
        elif name == "log_timezone":
            default = "UTC"
        context = {"backend": "Backend", "superuser-backend": "Backend"}.get(
            row["context"], row["context"].title()
        )
        values = ", ".join(map(literal, row["enumvals"] or []))
        fields = [
            f"name: {literal(name)}",
            f"kind: Kind::{row['vartype'].title()}",
            f"unit: {optional(row['unit'])}",
            f"context: Context::{context}",
            f"context_name: {literal(row['context'])}",
            f"min: {optional(row['min_val'])}",
            f"max: {optional(row['max_val'])}",
            f"enum_values: &[{values}]",
            f"category: {literal(row['category'])}",
            f"short_desc: {literal(row['short_desc'])}",
            f"extra_desc: {optional(row['extra_desc'])}",
            f"boot: {optional(row['boot_val'])}",
            f"default: {literal(default)}",
            f"restricted: {str(name in restricted).lower()}",
        ]
        lines.append("    Entry { " + ", ".join(fields) + " },")
    return "\n".join([*lines, "];", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = render()
    if args.check:
        if DESTINATION.read_text(encoding="utf-8") != output:
            parser.exit(1, f"{DESTINATION} is out of date\n")
    else:
        DESTINATION.write_text(output, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
