#!/usr/bin/env python3
"""Generate the PostgreSQL 18 routine-name inventory using only the stdlib.

Run with python -I scripts/postgres-functions/routine_names.py [--check].
"""

import argparse
import gzip
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "scripts/postgres-functions/postgres-18.0.json.gz"
OUTPUT = ROOT / "crates/giggles-core/src/relational/query/functions/pg18_routines.rs"

# PostgreSQL 18.6: SELECT word FROM pg_get_keywords() WHERE catcode <> 'U'
# (164 C/R/T), embedded from supplied pg186-nonunreserved-keywords.txt.
# Keep these embedded so regeneration needs no network.
NON_UNRESERVED_KEYWORDS = """
all analyse analyze and any array as asc asymmetric authorization between bigint binary bit boolean both case cast char character check coalesce collate collation column concurrently constraint create cross current_catalog current_date current_role current_schema current_time current_timestamp current_user dec decimal default deferrable desc distinct do else end except exists extract false fetch float for foreign freeze from full grant greatest group grouping having ilike in initially inner inout int integer intersect interval into is isnull join json json_array json_arrayagg json_exists json_object json_objectagg json_query json_scalar json_serialize json_table json_value lateral leading least left like limit localtime localtimestamp merge_action national natural nchar none normalize not notnull null nullif numeric offset on only or order out outer overlaps overlay placing position precision primary real references returning right row select session_user setof similar smallint some substring symmetric system_user table tablesample then time timestamp to trailing treat trim true union unique user using values varchar variadic verbose when where window with xmlattributes xmlconcat xmlelement xmlexists xmlforest xmlnamespaces xmlparse xmlpi xmlroot xmlserialize xmltable
""".split()


def render():
    with gzip.open(SOURCE, "rt", encoding="utf-8") as source:
        routines = json.load(source)["routines"]
    pairs = {(row["schema"], row["catalog"]["proname"]) for row in routines}
    if len(pairs) != 2798:
        raise ValueError(f"expected 2798 distinct routine pairs, got {len(pairs)}")
    if {schema for schema, _ in pairs} != {"pg_catalog", "information_schema"}:
        raise ValueError("unexpected routine schema in source inventory")
    keywords = sorted(set(NON_UNRESERVED_KEYWORDS))
    if len(keywords) != 164:
        raise ValueError(f"expected 164 distinct keywords, got {len(keywords)}")
    inventories = [
        ("PG_CATALOG", sorted(name for schema, name in pairs if schema == "pg_catalog")),
        ("INFORMATION_SCHEMA", sorted(name for schema, name in pairs if schema == "information_schema")),
        ("NON_UNRESERVED_KEYWORDS", keywords),
    ]
    if len(inventories[0][1]) != 2787 or len(inventories[1][1]) != 11:
        raise ValueError("unexpected per-schema routine counts")
    lines = [
        "// @generated by scripts/postgres-functions/routine_names.py; do not edit.",
        "// Routine source: scripts/postgres-functions/postgres-18.0.json.gz",
        "// Fields: routines[].schema and routines[].catalog.proname (2798 distinct pairs).",
        "// Keyword source: PostgreSQL 18.6:",
        "// SELECT word FROM pg_get_keywords() WHERE catcode <> 'U' (164 C/R/T).",
        "// Embedded from supplied pg186-nonunreserved-keywords.txt in the generator.",
        "",
    ]
    for symbol, names in inventories:
        lines.append(f"pub(super) const {symbol}: &[&str] = &[")
        lines.extend(f"    {json.dumps(name)}," for name in names)
        lines.extend(["];", ""])
    lines.extend([
        "#[cfg(test)]",
        "mod tests {",
        "    use super::{INFORMATION_SCHEMA, NON_UNRESERVED_KEYWORDS, PG_CATALOG};",
        "",
        "    #[test]",
        "    fn inventory_counts_and_sortedness() {",
        "        assert_eq!(PG_CATALOG.len(), 2787);",
        "        assert_eq!(INFORMATION_SCHEMA.len(), 11);",
        "        assert_eq!(NON_UNRESERVED_KEYWORDS.len(), 164);",
        "        for names in [PG_CATALOG, INFORMATION_SCHEMA, NON_UNRESERVED_KEYWORDS] {",
        "            assert!(names.windows(2).all(|pair| pair[0] < pair[1]));",
        "        }",
        "    }",
        "}",
        "",
    ])
    return "\n".join(lines).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated output differs")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_bytes() != expected:
            print(f"generated inventory differs: {OUTPUT}", file=sys.stderr)
            return 1
    else:
        OUTPUT.write_bytes(expected)
    print("routine inventory: 2798 distinct pairs (pg_catalog=2787, information_schema=11); keywords=164")
    return 0


if __name__ == "__main__":
    sys.exit(main())